"""Cross-check the D4 armlink samples with tools independent of each other, and record what FirmwareSight does.

For each build in fixtures/elf/d4-armlink/{base,target}:

1. **armlink's own totals**, from the `--info=totals` block of `firmware.map` (Total RO, Total RW, Total ROM).
2. **GNU readelf** (Arm GNU Toolchain, not Arm Compiler): the allocated sections of `firmware.axf`, summed by
   flags. RO = allocated and not writable; RW = writable PROGBITS; ZI = NOBITS.
3. **FirmwareSight's ELF reader** (`fwsight analyze --json` without a MAP): its Flash and RAM footprint.
4. **FirmwareSight with the armlink MAP** (`fwsight analyze --map`): what happens today. No adapter exists, so
   anything but a refusal or an Unknown is itself a finding.

Writes evidence/D4/CROSSCHECK.md and exits non-zero if (1) and (2) disagree. Nothing here is a support claim.

    python scripts/crosscheck_d4_armlink.py [--fwsight PATH]
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SAMPLES = ROOT / "fixtures" / "elf" / "d4-armlink"
OUT = ROOT / "evidence" / "D4" / "CROSSCHECK.md"


def run(cmd: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace", check=False)


def armlink_totals(map_text: str) -> dict[str, int]:
    out = {}
    for key, label in (("ro", "Total RO  Size"), ("rw", "Total RW  Size"), ("rom", "Total ROM Size")):
        match = re.search(re.escape(label) + r"[^\d]*(\d+)", map_text)
        out[key] = int(match.group(1)) if match else -1
    return out


def readelf_totals(axf: Path) -> dict[str, int]:
    result = run(["arm-none-eabi-readelf", "-S", "-W", str(axf)])
    if result.returncode != 0:
        sys.exit(f"readelf failed on {axf}: {result.stderr}")
    ro = rw = zi = 0
    rows = re.findall(r"\]\s+(\S+)\s+(\S+)\s+[0-9a-f]+\s+[0-9a-f]+\s+([0-9a-f]+)\s+\S+\s+([A-Z]*)", result.stdout)
    for _name, kind, size, flags in rows:
        if "A" not in flags:
            continue
        size_value = int(size, 16)
        if kind == "NOBITS":
            zi += size_value
        elif "W" in flags:
            rw += size_value
        else:
            ro += size_value
    return {"ro": ro, "rw_data": rw, "zi": zi, "rom": ro + rw, "ram": rw + zi}


def fwsight(fw: str, axf: Path, map_file: Path | None) -> str:
    cmd = [fw, "analyze", str(axf.relative_to(ROOT)), "--json"]
    if map_file is not None:
        cmd += ["--map", str(map_file.relative_to(ROOT))]
    result = run(cmd)
    if result.returncode != 0:
        first = (result.stderr.strip().splitlines() or ["(no message)"])[0]
        return f"exit {result.returncode}: {first[:160]}"
    try:
        doc = json.loads(result.stdout)
    except json.JSONDecodeError:
        return "exit 0, output not JSON"
    memory = doc.get("memory", {})

    def figure(key: str) -> str:
        node = memory.get(key) or {}
        return f"{node.get('bytes')} ({node.get('state')}, {node.get('classification')})"

    names = ", ".join(c.get("sectionName", "?") for c in memory.get("contributions", []))
    return (
        f"exit 0: Flash {figure('nonvolatileImageFootprint')}; RAM {figure('runtimeRamFootprint')}; "
        f"layout `{memory.get('layoutSource')}`; sections charged: {names}"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fwsight", default=str(ROOT / "target" / "debug" / "fwsight.exe"))
    args = parser.parse_args()
    version = run(["arm-none-eabi-readelf", "--version"]).stdout.splitlines()[0].strip()
    lines = [
        "# D4 armlink samples: independent cross-check",
        "",
        "Generated by `scripts/crosscheck_d4_armlink.py`. Not a support claim (Standing Owner rule 3).",
        "",
        f"- Independent reader: `{version}`.",
        "- RO = allocated, not writable; RW = writable PROGBITS; ZI = NOBITS. ROM = RO + RW; RAM = RW + ZI.",
        "",
        "| Build | armlink Total RO / RW / ROM | readelf RO / RW data / ZI | readelf ROM / RAM | agree |",
        "|---|---|---|---|---|",
    ]
    ok = True
    fw_rows = []
    for name in ("base", "target"):
        directory = SAMPLES / name
        totals = armlink_totals((directory / "firmware.map").read_text(encoding="utf-8", errors="replace"))
        elf = readelf_totals(directory / "firmware.axf")
        agree = totals["ro"] == elf["ro"] and totals["rw"] == elf["ram"] and totals["rom"] == elf["rom"]
        ok &= agree
        lines.append(
            f"| `{name}` | {totals['ro']} / {totals['rw']} / {totals['rom']} | {elf['ro']} / {elf['rw_data']} / "
            f"{elf['zi']} | {elf['rom']} / {elf['ram']} | {'YES' if agree else 'NO'} |"
        )
        fw_rows.append((name, fwsight(args.fwsight, directory / "firmware.axf", None),
                        fwsight(args.fwsight, directory / "firmware.axf", directory / "firmware.map")))
    lines += [
        "",
        "## What FirmwareSight does with these files today",
        "",
        "| Build | `fwsight analyze firmware.axf` | `fwsight analyze firmware.axf --map firmware.map` |",
        "|---|---|---|",
        *[f"| `{n}` | {a} | {b} |" for n, a, b in fw_rows],
        "",
    ]
    diff = run([args.fwsight, "diff", "fixtures/elf/d4-armlink/base/firmware.axf",
                "fixtures/elf/d4-armlink/target/firmware.axf"])
    lines += [
        "## `fwsight diff` base → target (ELF only)",
        "",
        "The source of the Compare observations in `evidence/D4/README.md` and `06_DELIVERY/24` §2.2.",
        "",
        "```text",
        *diff.stdout.rstrip().splitlines(),
        "```",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
