//! GNU ld MAP adapter.
//!
//! This exists because the section header table cannot express where the *loader* stored a
//! section, and `04_TECH/23_MEMORY_ACCOUNTING_MODEL.md` ranks supported MAP region evidence
//! above anything derivable from names. GNU ld writes both facts into its MAP: a
//! `Memory Configuration` table, and a `load address 0x...` suffix on output sections whose
//! load address differs from their runtime address.
//!
//! Adapters are split per toolchain (`04_TECH/03_FORMAT_SUPPORT.md`). An ArmClang or IAR MAP is
//! reported as unsupported; it is never fed to this parser.

use crate::error::ArtifactError;
use firmwaresight_core::domain::memory::{MemoryLayout, MemoryRegion};

pub const ADAPTER_ID: &str = "gnu_ld";

/// One output-section placement line from the memory map.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MapPlacement {
    pub section: String,
    /// Runtime address.
    pub address: u64,
    pub size: u64,
    /// Where the bytes were stored, when the line says so explicitly. GNU ld omits it when it equals the
    /// runtime address.
    pub load_address: Option<u64>,
    /// Set when the MAP cannot say where the bytes were stored (ADR-0036: an armlink region without a
    /// `Load base`, or with compressed data). The section's load address is then recorded as unknown with
    /// this reason, never assumed equal to its runtime address.
    pub load_unknown: Option<&'static str>,
    /// The region's runtime size when the ELF cannot show it: an armlink region whose RW data is
    /// compressed keeps the *compressed* bytes in its ELF section, so its runtime size comes from the MAP's
    /// region `Size` instead (ADR-0036 A1). `None` everywhere else.
    pub runtime_size: Option<u64>,
    pub line: usize,
}

/// One symbol contribution record.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MapSymbol {
    pub address: u64,
    pub name: String,
    pub line: usize,
}

/// One input-section row attributed to the object it came from (ADR-0033 D1).
///
/// `object` is the ADR-0033 D2 key: `libx.a(y.o)` for an archive member, otherwise a path relative to the
/// directory every object of the MAP shares, or a bare file name when the path was absolute outside that
/// directory. It is never a host path.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MapObjectContribution {
    pub input_section: String,
    /// The output section the row sits under, when the MAP names one above it.
    pub output_section: Option<String>,
    pub address: u64,
    pub size: u64,
    pub object: String,
    pub archive: Option<String>,
    pub member: String,
    pub line: usize,
}

/// Bytes the linker placed itself: padding (`*fill*`) or generated stubs. Never an object's.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LinkerBytesKind {
    Fill,
    LinkerStubs,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MapLinkerBytes {
    pub output_section: Option<String>,
    pub address: u64,
    pub size: u64,
    pub kind: LinkerBytesKind,
    pub line: usize,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MapEvidence {
    pub adapter_id: &'static str,
    pub regions: Vec<MemoryRegion>,
    pub placements: Vec<MapPlacement>,
    pub symbols: Vec<MapSymbol>,
    pub object_contributions: Vec<MapObjectContribution>,
    /// Linker-generated bytes, kept apart so they are never charged to an object (ADR-0033 D1).
    pub linker_bytes: Vec<MapLinkerBytes>,
    /// The `OUTPUT(...)` line records the emulation the linker used.
    pub emulation: Option<String>,
}

impl MapEvidence {
    /// Region table as the memory model wants it. Attributed to the MAP so the accounting
    /// basis is level 2, not a guess.
    #[must_use]
    pub fn layout(&self) -> MemoryLayout {
        MemoryLayout {
            regions: self.regions.clone(),
            source: firmwaresight_core::domain::memory::LayoutSource::MapMemoryConfiguration,
        }
    }

    #[must_use]
    pub fn placement_for(&self, section_name: &str) -> Option<&MapPlacement> {
        self.placements.iter().find(|p| p.section == section_name)
    }

    /// The placement for a section of this name that holds `address`. armlink names output sections
    /// after execution regions, and one region can produce two sections of one name (RW data and ZI), so
    /// the address chooses; a GNU placement starts exactly at its section.
    #[must_use]
    pub fn placement_containing(&self, section_name: &str, address: u64) -> Option<&MapPlacement> {
        self.placements
            .iter()
            .filter(|p| p.section == section_name)
            .find(|p| address >= p.address && address - p.address < p.size.max(1))
            .or_else(|| self.placement_for(section_name))
    }
}

/// Parse a MAP from whichever supported linker wrote it (ADR-0036): armlink's image map goes to the
/// armlink adapter, GNU ld's to the GNU adapter, and anything else is refused as before.
///
/// # Errors
///
/// `MapUnsupported` for a foreign or unrecognized MAP; `MapParseFailed` when a supported MAP is malformed.
pub fn parse_any(text: &str) -> Result<MapEvidence, ArtifactError> {
    // GNU ld's own banner wins: a GNU map that happens to quote armlink's words is still a GNU map.
    if crate::map_armlink::detect(text) && !is_gnu_ld(text) {
        return crate::map_armlink::parse(text);
    }
    if crate::map_armlink::mentions_armlink(text) && !is_gnu_ld(text) {
        return Err(ArtifactError::MapUnsupported {
            detected: "an armlink file without an image memory map (link with --map)".to_owned(),
        });
    }
    parse(text)
}

/// Decide whether this text is a MAP this adapter may parse.
///
/// Returns `Ok(true)` for GNU ld, `Err(MapUnsupported)` for a recognized foreign toolchain, and
/// `Ok(false)` when nothing identifies it at all. A negative answer is never a silent partial
/// parse.
pub fn detect(text: &str) -> Result<bool, ArtifactError> {
    let foreign = [
        "ARM Linker map information",
        "Tool: armlink",
        "*** MAP FILE",
        "IAR ELF Linker",
        "IAR Linker",
        "RN32/RN42",
        "Linker Map File",
    ];
    for marker in foreign {
        if text.contains(marker) {
            return Err(ArtifactError::MapUnsupported {
                detected: format!("recognized a non-GNU linker MAP banner: {marker}"),
            });
        }
    }
    // A foreign header outranks incidental GNU words in scripts, notes or a
    // concatenated file. Refusal is safer than attributing foreign placement as GNU.
    Ok(is_gnu_ld(text))
}

/// Whether this text carries a GNU ld banner.
///
/// The whole text is searched, not a head window. GNU ld prints its banners behind a preamble whose
/// length the project does not control — an `Archive member included to satisfy reference by file
/// (symbol)` block for every symbol pulled from a static library, and a `Discarded input sections`
/// block under `--gc-sections` — so a fixed window refuses ordinary vendor-HAL builds. This is the
/// same ground [`detect`] already searches for the foreign-toolchain banners.
fn is_gnu_ld(text: &str) -> bool {
    text.contains("Linker script and memory map") || text.contains("Memory Configuration")
}

/// Parse a GNU ld MAP.
pub fn parse(text: &str) -> Result<MapEvidence, ArtifactError> {
    if !detect(text)? {
        return Err(ArtifactError::MapUnsupported {
            detected: "no GNU ld memory-map banner was found".to_owned(),
        });
    }

    let mut regions = Vec::new();
    let mut placements = Vec::new();
    let mut symbols = Vec::new();
    let mut raw_contributions: Vec<RawContribution> = Vec::new();
    let mut linker_bytes = Vec::new();
    let mut emulation = None;

    let mut in_region_table = false;
    // ADR-0033 D1: object rows count only inside the memory map. The `Discarded input sections` block
    // above it lists sections --gc-sections removed, and those are not in the image.
    let mut in_memory_map = false;
    let mut current_output: Option<String> = None;
    // GNU ld wraps a name longer than its column: the name on one line, the numbers on the next.
    let mut pending_output: Option<String> = None;
    let mut pending_input: Option<String> = None;

    for (index, raw) in text.lines().enumerate() {
        let line = index + 1;

        if raw.trim() == "Memory Configuration" {
            in_region_table = true;
            continue;
        }
        if in_region_table {
            // GNU ld prints a blank line between the banner and the column headers, so blanks
            // are skipped rather than treated as the end of the table.
            if raw.trim().is_empty() {
                continue;
            }
            if raw.trim_start().starts_with("Name") {
                continue;
            }
            if let Some(region) = parse_region_line(raw, line)? {
                regions.push(region);
                continue;
            }
            // First non-blank line that is not a row ends the table; fall through to it.
            in_region_table = false;
        }

        if raw.trim() == "Linker script and memory map" {
            in_memory_map = true;
            continue;
        }

        if let Some(rest) = raw.strip_prefix("OUTPUT(") {
            emulation = Some(rest.trim_end_matches(')').trim().to_owned());
            continue;
        }

        // The second half of a wrapped output section: `<indent>0xADDR 0xSIZE [load address 0xADDR]`.
        // It only names the section the following rows sit under (ADR-0033). It is deliberately not a
        // placement: placements feed region and load-address evidence, and widening that is not this
        // ADR's decision (non-allocated sections such as `.ARM.attributes` wrap at address 0).
        if let Some(name) = pending_output.take() {
            let joined = format!("{name} {}", raw.trim());
            if let Some(placement) = parse_placement_line(&joined, line)? {
                current_output = Some(placement.section);
                continue;
            }
        }
        // The second half of a wrapped input section: `<indent>0xADDR 0xSIZE object`.
        if let Some(row) = pending_input
            .take()
            .and_then(|name| parse_row_numbers(&name, raw))
        {
            if in_memory_map {
                record_row(
                    row,
                    &current_output,
                    line,
                    &mut raw_contributions,
                    &mut linker_bytes,
                );
            }
            continue;
        }

        // Column-zero output section: `.name 0xADDR 0xSIZE [load address 0xADDR]`.
        if let Some(placement) = parse_placement_line(raw, line)? {
            current_output = Some(placement.section.clone());
            placements.push(placement);
            continue;
        }
        // A column-zero name alone is an output section whose numbers wrapped to the next line.
        if raw.starts_with('.') && raw.split_whitespace().count() == 1 {
            pending_output = Some(raw.trim().to_owned());
            continue;
        }
        // An indented name alone is an input section whose numbers wrapped to the next line.
        if raw.starts_with([' ', '\t']) {
            let fields: Vec<&str> = raw.split_whitespace().collect();
            if fields.len() == 1 && is_input_section_name(fields[0]) {
                pending_input = Some(fields[0].to_owned());
                continue;
            }
        }
        // Indented input section on one line: ` .name 0xADDR 0xSIZE object` (also COMMON and *fill*).
        if let Some(row) = parse_input_row(raw) {
            if in_memory_map {
                record_row(
                    row,
                    &current_output,
                    line,
                    &mut raw_contributions,
                    &mut linker_bytes,
                );
            }
            continue;
        }
        // Address-only continuation line naming a symbol.
        if let Some(symbol) = parse_symbol_line(raw, line) {
            symbols.push(symbol);
        }
    }
    let object_contributions = normalize_contributions(raw_contributions);

    if regions.is_empty() {
        return Err(ArtifactError::MapParseFailed {
            line: 0,
            detail: "the MAP declared no memory regions, so no region evidence exists".to_owned(),
        });
    }

    Ok(MapEvidence {
        adapter_id: ADAPTER_ID,
        regions,
        placements,
        symbols,
        object_contributions,
        linker_bytes,
        emulation,
    })
}

fn parse_hex(token: &str) -> Option<u64> {
    let token = token.strip_prefix("0x").or(token.strip_prefix("0X"))?;
    if token.is_empty() || !token.chars().all(|c| c.is_ascii_hexdigit()) {
        return None;
    }
    u64::from_str_radix(token, 16).ok()
}

fn parse_region_line(raw: &str, line: usize) -> Result<Option<MemoryRegion>, ArtifactError> {
    let fields: Vec<&str> = raw.split_whitespace().collect();
    if fields.len() < 3 {
        return Ok(None);
    }
    let (name, origin, length) = (fields[0], fields[1], fields[2]);
    let Some(origin) = parse_hex(origin) else {
        // Not a region row; let the caller fall through to other line kinds.
        return Ok(None);
    };
    let Some(length) = parse_hex(length) else {
        return Ok(None);
    };
    if name == "*default*" {
        return Ok(Some(MemoryRegion::new(
            name,
            origin,
            length,
            "",
            format!("map.line{line}"),
        )));
    }
    let attributes = fields.get(3).copied().unwrap_or("");
    Ok(Some(MemoryRegion::new(
        name,
        origin,
        length,
        attributes,
        format!("map.line{line}"),
    )))
}

fn parse_placement_line(raw: &str, line: usize) -> Result<Option<MapPlacement>, ArtifactError> {
    // Output sections start in column zero; input sections are indented.
    if raw.is_empty() || raw.starts_with([' ', '\t']) || !raw.starts_with('.') {
        return Ok(None);
    }
    let head = raw.split_whitespace().next().unwrap_or_default();
    if !head.starts_with('.') {
        return Ok(None);
    }
    let fields: Vec<&str> = raw.split_whitespace().collect();
    if fields.len() < 3 {
        return Ok(None);
    }
    let (Some(address), Some(size)) = (parse_hex(fields[1]), parse_hex(fields[2])) else {
        return Ok(None);
    };

    // `... load address 0x...` is the explicit statement of where the bytes were stored.
    let load_address = match fields.iter().position(|f| *f == "load") {
        Some(position) => match fields.get(position + 2) {
            Some(token) => match parse_hex(token) {
                Some(value) => Some(value),
                None => {
                    return Err(ArtifactError::MapParseFailed {
                        line,
                        detail: "a 'load address' record did not carry a hex value".to_owned(),
                    });
                }
            },
            None => {
                return Err(ArtifactError::MapParseFailed {
                    line,
                    detail: "a 'load address' record was truncated".to_owned(),
                });
            }
        },
        None => None,
    };

    Ok(Some(MapPlacement {
        section: head.to_owned(),
        address,
        size,
        load_address,
        load_unknown: None,
        runtime_size: None,
        line,
    }))
}

/// An input-section row before its object is normalized (shared with the armlink adapter).
pub(crate) struct RawContribution {
    pub(crate) input_section: String,
    pub(crate) output_section: Option<String>,
    pub(crate) address: u64,
    pub(crate) size: u64,
    pub(crate) object: String,
    pub(crate) line: usize,
}

/// The parts of an input-section row: its name, address, size and what it came from.
struct InputRow {
    name: String,
    address: u64,
    size: u64,
    /// The object reference, `linker stubs`, or empty for `*fill*`.
    source: String,
}

fn is_input_section_name(token: &str) -> bool {
    token.starts_with('.') || token == "COMMON" || token == "*fill*"
}

/// `<indent>name 0xADDR 0xSIZE source...` on one line.
fn parse_input_row(raw: &str) -> Option<InputRow> {
    if !raw.starts_with([' ', '\t']) {
        return None;
    }
    let mut fields = raw.split_whitespace();
    let name = fields.next()?;
    if !is_input_section_name(name) {
        return None;
    }
    let rest: Vec<&str> = fields.collect();
    if rest.len() < 2 {
        return None;
    }
    let address = parse_hex(rest[0])?;
    let size = parse_hex(rest[1])?;
    let source = rest[2..].join(" ");
    // A row with no source is only meaningful as padding.
    if source.is_empty() && name != "*fill*" {
        return None;
    }
    Some(InputRow {
        name: name.to_owned(),
        address,
        size,
        source,
    })
}

/// The numbers line of a wrapped input section, joined with the name held from the line above.
fn parse_row_numbers(name: &str, raw: &str) -> Option<InputRow> {
    if !raw.starts_with([' ', '\t']) {
        return None;
    }
    let fields: Vec<&str> = raw.split_whitespace().collect();
    if fields.len() < 2 {
        return None;
    }
    let address = parse_hex(fields[0])?;
    let size = parse_hex(fields[1])?;
    let source = fields[2..].join(" ");
    if source.is_empty() && name != "*fill*" {
        return None;
    }
    Some(InputRow {
        name: name.to_owned(),
        address,
        size,
        source,
    })
}

fn record_row(
    row: InputRow,
    output: &Option<String>,
    line: usize,
    contributions: &mut Vec<RawContribution>,
    linker_bytes: &mut Vec<MapLinkerBytes>,
) {
    if row.size == 0 {
        return;
    }
    let kind = if row.name == "*fill*" {
        Some(LinkerBytesKind::Fill)
    } else if row.source == "linker stubs" {
        Some(LinkerBytesKind::LinkerStubs)
    } else {
        None
    };
    if let Some(kind) = kind {
        linker_bytes.push(MapLinkerBytes {
            output_section: output.clone(),
            address: row.address,
            size: row.size,
            kind,
            line,
        });
        return;
    }
    contributions.push(RawContribution {
        input_section: row.name,
        output_section: output.clone(),
        address: row.address,
        size: row.size,
        object: row.source,
        line,
    });
}

/// A path split into components, with whether it was absolute on any host.
fn components(path: &str) -> (bool, Vec<String>) {
    let unified = path.replace('\\', "/");
    let absolute = unified.starts_with('/')
        || unified.starts_with("//")
        || (unified.len() >= 2
            && unified.as_bytes()[1] == b':'
            && unified.as_bytes()[0].is_ascii_alphabetic());
    let parts = unified
        .split('/')
        .filter(|part| !part.is_empty() && *part != ".")
        .map(str::to_owned)
        .collect();
    (absolute, parts)
}

/// How many leading components of `parts` are the root itself rather than directories: a drive
/// (`C:`), a UNC `server/share`, or a `\\?\` device prefix with what it names. POSIX `/` is not a
/// component at all, so it counts zero. Re-review 2 S2-1: counting `C:` or `server/share` as directories
/// made `C:/Users` as shallow as `/home` looked deep enough to anchor a key.
fn root_len(path: &str, parts: &[String]) -> usize {
    let drive = |part: &String| {
        part.len() == 2 && part.ends_with(':') && part.as_bytes()[0].is_ascii_alphabetic()
    };
    let unified = path.replace('\\', "/");
    let length = if unified.starts_with("//") {
        match parts.first().map(String::as_str) {
            Some("?" | ".") => match parts.get(1) {
                Some(part) if drive(part) => 2,
                Some(part) if part.eq_ignore_ascii_case("UNC") => 4,
                _ => 2,
            },
            _ => 2,
        }
    } else if parts.first().is_some_and(drive) {
        1
    } else {
        0
    };
    length.min(parts.len())
}

/// `dir/libx.a(member.o)` splits into the archive path and the member; anything else has no archive.
fn split_archive(object: &str) -> (Option<&str>, &str) {
    if let (Some(open), true) = (object.rfind('('), object.ends_with(')'))
        && open > 0
    {
        return (Some(&object[..open]), &object[open + 1..object.len() - 1]);
    }
    (None, object)
}

fn file_name(parts: &[String]) -> String {
    parts.last().cloned().unwrap_or_default()
}

/// The longest run of leading components every path in `paths` shares.
fn common_prefix(paths: &[&[String]]) -> usize {
    let Some((first, rest)) = paths.split_first() else {
        return 0;
    };
    let mut length = first.len();
    for other in rest {
        length = first
            .iter()
            .zip(other.iter())
            .take(length)
            .take_while(|(a, b)| a == b)
            .count();
    }
    length
}

/// ADR-0033 D2: no host path survives.
///
/// - An archive member is `archive(member)`, both reduced to their file names.
/// - A relative object path without `..` keeps its directories below the directory every such path
///   shares (`build/app/sensors/imu.o` next to `build/app/main.o` becomes `sensors/imu.o`). A relative
///   path names nothing outside the link's own working directory.
/// - Any other path (absolute on either host, or climbing out with `..`) is cut at the shallowest
///   directory above it that itself directly holds an object of this link and lies at least two
///   levels below a root, so only directories *below* an object directory survive. A project under
///   `C:/Users/<name>/proj/build/app` keeps `sensors/imu.o`; a toolchain `crti.o` under
///   `/usr/lib/gcc/...` becomes `crti.o`; an object lying directly in `C:/` or `/` anchors nothing
///   (review S1 and its re-review).
/// - When two different objects still end with the same key, the first in MAP order keeps it and the
///   others become `key#2`, `key#3`. A collision never borrows directories from the path, because the
///   only directories that tell two unrelated roots apart are the machine's (re-review S1).
/// - A final guard reduces any key that still reads as a host path to its file name.
pub(crate) fn normalize_contributions(raw: Vec<RawContribution>) -> Vec<MapObjectContribution> {
    /// The shallowest directory depth that may anchor a key: `C:/Users` or `/home/alice` and deeper,
    /// never a drive root, `/` or a single top-level directory.
    const MIN_ANCHOR_DEPTH: usize = 2;

    // Split every non-archive object once, and classify it.
    let split: Vec<Option<(bool, Vec<String>, usize)>> = raw
        .iter()
        .map(|row| {
            if split_archive(&row.object).0.is_some() {
                return None;
            }
            let (absolute, parts) = components(&row.object);
            let outside = absolute || parts.iter().any(|part| part == "..");
            let root = root_len(&row.object, &parts);
            Some((outside, parts, root))
        })
        .collect();

    // The directory every relative, in-tree object shares.
    let relative_dirs: Vec<&[String]> = split
        .iter()
        .flatten()
        .filter(|(outside, _, _)| !outside)
        .map(|(_, parts, _)| &parts[..parts.len().saturating_sub(1)])
        .collect();
    let relative_root = common_prefix(&relative_dirs);

    // Directories that directly hold an out-of-tree object, deep enough to be a project's own.
    let anchors: Vec<&[String]> = split
        .iter()
        .flatten()
        .filter(|(outside, _, _)| *outside)
        .map(|(_, parts, root)| (&parts[..parts.len().saturating_sub(1)], *root))
        .filter(|(dir, root)| dir.len() >= root + MIN_ANCHOR_DEPTH)
        .map(|(dir, _)| dir)
        .collect();
    let anchored = |parts: &[String]| -> String {
        let dir = &parts[..parts.len().saturating_sub(1)];
        let cut = anchors
            .iter()
            .filter(|anchor| dir.starts_with(anchor))
            .map(|anchor| anchor.len())
            .min()
            .unwrap_or(dir.len());
        parts[cut..].join("/")
    };
    let guarded = |key: String, parts: &[String]| -> String {
        let reads_as_path = key.contains(':')
            || key.starts_with('/')
            || key.contains('\\')
            || key.split('/').any(|part| part == "..");
        if reads_as_path { file_name(parts) } else { key }
    };

    // First pass: every row's key before collisions are told apart.
    let base_keys: Vec<(Option<String>, String, String)> = raw
        .iter()
        .zip(split.iter())
        .map(|(row, split)| match split {
            None => {
                let (archive, member) = split_archive(&row.object);
                let archive = file_name(&components(archive.unwrap_or_default()).1);
                let member = file_name(&components(member).1);
                let key = format!("{archive}({member})");
                (Some(archive), member, key)
            }
            Some((outside, parts, _)) => {
                let key = if *outside {
                    anchored(parts)
                } else {
                    parts[relative_root.min(parts.len().saturating_sub(1))..].join("/")
                };
                (None, file_name(parts), guarded(key, parts))
            }
        })
        .collect();

    // Second pass: one key per distinct object, across relative, out-of-tree and archive rows alike.
    // Two rows name the same object only when the linker printed the same text for it.
    let mut owners: std::collections::BTreeMap<String, Vec<String>> =
        std::collections::BTreeMap::new();
    for (row, (_, _, key)) in raw.iter().zip(&base_keys) {
        let list = owners.entry(key.clone()).or_default();
        if !list.contains(&row.object) {
            list.push(row.object.clone());
        }
    }

    // The suffixed key for each later owner, skipping any key another row already has: a real file
    // named `main.o#2` keeps its name, and the generated one moves on to `main.o#3` (re-review 2 S3).
    let mut taken: std::collections::BTreeSet<String> = owners.keys().cloned().collect();
    let mut renamed: std::collections::BTreeMap<(String, String), String> =
        std::collections::BTreeMap::new();
    for (key, list) in &owners {
        let mut next = 2_usize;
        for object in list.iter().skip(1) {
            let mut candidate = format!("{key}#{next}");
            while taken.contains(&candidate) {
                next += 1;
                candidate = format!("{key}#{next}");
            }
            taken.insert(candidate.clone());
            renamed.insert((key.clone(), object.clone()), candidate);
            next += 1;
        }
    }

    raw.into_iter()
        .zip(base_keys)
        .map(|(row, (archive, member, key))| {
            let key = renamed
                .get(&(key.clone(), row.object.clone()))
                .cloned()
                .unwrap_or(key);
            MapObjectContribution {
                input_section: row.input_section,
                output_section: row.output_section,
                address: row.address,
                size: row.size,
                object: key,
                archive,
                member,
                line: row.line,
            }
        })
        .collect()
}

fn parse_symbol_line(raw: &str, line: usize) -> Option<MapSymbol> {
    if !raw.starts_with([' ', '\t']) {
        return None;
    }
    let fields: Vec<&str> = raw.split_whitespace().collect();
    if fields.len() != 2 {
        return None;
    }
    let address = parse_hex(fields[0])?;
    let name = fields[1];
    if name.starts_with('.') || name.starts_with("0x") {
        return None;
    }
    Some(MapSymbol {
        address,
        name: name.to_owned(),
        line,
    })
}

