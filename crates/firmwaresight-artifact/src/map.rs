    fn by_key<'a>(evidence: &'a MapEvidence, key: &str) -> &'a MapObjectContribution {
        evidence
            .object_contributions
            .iter()
            .find(|c| c.object == key)
            .unwrap_or_else(|| {
                panic!(
                    "no contribution keyed {key}: {:?}",
                    evidence.object_contributions
                )
            })
    }

    #[test]
    fn every_row_shape_is_attributed_without_a_host_path() {
        let evidence = parse(MAP).expect("parses");
        let keys: Vec<&str> = evidence
            .object_contributions
            .iter()
            .map(|c| c.object.as_str())
            .collect();
        assert_eq!(
            keys,
            [
                "main.o",
                "sensors/imu.o",
                "libdrv.a(uart.o)",
                "libc_nano.a(lib_a-memcpy.o)",
                "main.o",
                "main.o",
                "sensors/imu.o",
            ]
        );
        for c in &evidence.object_contributions {
            assert!(
                !c.object.contains(':') && !c.object.starts_with('/'),
                "host path kept: {}",
                c.object
            );
        }
    }

    #[test]
