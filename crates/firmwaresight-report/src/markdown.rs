//! Markdown reports (R6, ADR-0034 D6): one GFM document per analysis, comparison and Gate run, for a pull
//! request, an issue or a review record.
//!
//! They read in the report grammar every other edition uses (`03_DESIGN/09` §8.1): a masthead naming the
//! report and its subject, the answer, the facts as tables, the evidence, the limits written as facts, and
//! a footer naming the generator. Four rules hold for every document here:
//!
//! - **No HTML.** A state is a word in bold (`**BLOCK**`), never a colour or an inline element.
//! - **Deterministic.** The same input writes the same bytes: no clock, no host name, no path.
//! - **Absent and Unknown keep their words.** A side that does not exist reads "not present", a figure
//!   that was never measured reads "unknown", and neither becomes `0`.
//! - **Text from a file is inert.** A section, symbol or file name is escaped, so a name cannot start a
//!   heading, a link or a table cell of its own, and control characters are shown, not sent.
//!
//! A Markdown report is not part of a release bundle (ADR-0028): the bundle's contents are fixed by its
//! manifest, and this is a reading copy.

use firmwaresight_core::domain::diff::{ChangeKind, Contributor, DiffResult};
use firmwaresight_core::domain::gate::FindingState;
use firmwaresight_core::domain::memory::{MemoryRegionUsage, RegionUsageState};

use crate::dto::AnalyzeResultDto;
use crate::gate::GateResultsDto;
use crate::gate_render::{STATE_ORDER, sentence_from_words};
use crate::render::{budget_line, safe_display_text};

/// Text from an artifact or a policy, made inert for Markdown: control characters are shown escaped,
/// every character Markdown gives a meaning to is backslash-escaped, and a line break becomes a space so a
/// value cannot leave its table cell.
#[must_use]
pub fn escape(raw: &str) -> String {
    let safe = safe_display_text(raw);
    let mut out = String::with_capacity(safe.len());
    for ch in safe.chars() {
        match ch {
            // Every escaped value sits mid-line or in a table cell, where only these characters can open
            // emphasis, code, a link, raw HTML, a strikethrough or a new cell. A dot or a dash stays
            // readable: `firmware.elf`, never `firmware\.elf`.
            '\\' | '`' | '*' | '_' | '[' | ']' | '<' | '>' | '|' | '~' => {
                out.push('\\');
                out.push(ch);
            }
            '\n' | '\r' => out.push(' '),
            _ => out.push(ch),
        }
    }
    out
}

/// A value that is an identifier (a digest, an id, a locator) as inline code. Backticks inside it would
/// end the span, so they are replaced; nothing else in a code span is interpreted.
fn code(raw: &str) -> String {
    format!("`{}`", safe_display_text(raw).replace('`', "'"))
}

fn footer(out: &mut String, kind: &str) {
    out.push_str("\n---\n\n");
    out.push_str(&format!(
        "Generated by FirmwareSight {} ({kind}). The same input produces the same document. No network, no path, no host name.\n",
        env!("CARGO_PKG_VERSION")
    ));
}

fn bytes(value: Option<u64>) -> String {
    value.map_or_else(|| "unknown".to_owned(), |bytes| format!("{bytes} bytes"))
}

/// `fwsight analyze --markdown`, and the desktop's Analyze export.
#[must_use]
pub fn analysis(value: &AnalyzeResultDto, regions: &[MemoryRegionUsage]) -> String {
    let mut out = String::from("# FirmwareSight · Analysis report\n\n");
    out.push_str(&format!(
        "**Build:** {} · SHA-256 {}\n\n",
        escape(&value.artifact.file_name),
        code(&value.artifact.sha256)
    ));
    out.push_str(&format!(
        "> Nonvolatile / load image: **{}**. Runtime RAM: **{}**.\n\n",
        escape(&budget_line(&value.memory.nonvolatile_image_footprint)),
        escape(&budget_line(&value.memory.runtime_ram_footprint))
    ));

    out.push_str("## Facts\n\n| Fact | Value |\n|---|---|\n");
    for (label, fact) in [
        ("Size", format!("{} bytes", value.artifact.byte_size)),
        (
            "Format",
            escape(&format!(
                "{} {}-bit {}",
                value.artifact.architecture, value.artifact.bitness, value.artifact.endianness
            )),
        ),
        (
            "Evidence basis",
            escape(&format!(
                "{} (layout: {})",
                value
                    .memory
                    .weakest_evidence_basis
                    .unwrap_or("no allocatable sections"),
                value.memory.layout_source
            )),
        ),
        (
            "Counts",
            format!(
                "{} sections · {} symbols · {} evidence items",
                value.counts.sections, value.counts.symbols, value.counts.evidence
            ),
        ),
    ] {
        out.push_str(&format!("| {label} | {fact} |\n"));
    }

    if !value.memory.contributions.is_empty() {
        out.push_str("\n## Section contributions\n\n| Section | Nonvolatile | Runtime RAM | Class | Basis |\n|---|---:|---:|---|---|\n");
        for row in &value.memory.contributions {
            out.push_str(&format!(
                "| {} | {} | {} | {} | {} |\n",
                row.section_name
                    .as_deref()
                    .map_or_else(|| "unknown section".to_owned(), escape),
                bytes(row.nonvolatile_bytes),
                bytes(row.runtime_ram_bytes),
                row.classification,
                escape(row.evidence_basis)
            ));
        }
    }

    out.push_str("\n## Memory regions\n\n");
    if regions.is_empty() {
        out.push_str(&format!(
            "Unknown: no supported memory-region table is available (layout: {}).\n",
            escape(value.memory.layout_source)
        ));
    } else {
        out.push_str(
            "| Region | Capacity | Mapped section ranges | Evidence |\n|---|---:|---:|---|\n",
        );
        for region in regions {
            let used = match (region.used_bytes, region.state) {
                (Some(bytes), RegionUsageState::Exact) => format!("{bytes} bytes"),
                (Some(bytes), RegionUsageState::Partial) => format!("at least {bytes} bytes"),
                _ => "unknown".to_owned(),
            };
            out.push_str(&format!(
                "| {} | {} | {used} | {} |\n",
                escape(&region.name),
                bytes(region.capacity_bytes),
                code(&region.evidence_id)
            ));
        }
        out.push_str("\nA mapped section range is not free space: the region table and the section intervals do not prove contiguous allocatable space.\n");
    }

    out.push_str("\n## Capabilities\n\n| Capability | State |\n|---|---|\n");
    for (label, field) in [
        ("ELF", value.capabilities.elf),
        ("Sections", value.capabilities.sections),
        ("Symbols", value.capabilities.symbols),
        ("Debug info", value.capabilities.debug_info),
        ("MAP", value.capabilities.map),
        ("Object attribution", value.capabilities.object_attribution),
        ("Git", value.capabilities.git),
    ] {
        out.push_str(&format!("| {label} | {field} |\n"));
    }

    out.push_str("\n## Limits\n\n");
    out.push_str("- Every figure comes from the ELF and, when given, the GNU ld MAP.\n");
    out.push_str("- An unknown figure is written as unknown, never as 0.\n");
    out.push_str("- BIN and HEX files are not analyzed.\n");
    footer(&mut out, "analysis");
    out
}

fn delta_text(delta: Option<i64>) -> String {
    match delta {
        Some(value) if value > 0 => format!("▲{value} bytes"),
        Some(value) if value < 0 => format!("▼{} bytes", value.unsigned_abs()),
        Some(_) => "0 bytes".to_owned(),
        None => "unknown".to_owned(),
    }
}

fn side(bytes: Option<u64>) -> String {
    bytes.map_or_else(
        || "not present".to_owned(),
        |bytes| format!("{bytes} bytes"),
    )
}

fn contributors(out: &mut String, title: &str, rows: &[Contributor]) {
    out.push_str(&format!("\n### {title}\n\n"));
    if rows.is_empty() {
        out.push_str("None.\n");
        return;
    }
    out.push_str("| Name | Change | Δ | Size |\n|---|---|---:|---:|\n");
    for row in rows {
        // An Added or Removed row has no delta: one side does not exist, which is not "unknown". A size
        // the row never recorded is unknown, unless the row is the one that is gone.
        let delta = match (row.delta, row.change) {
            (Some(_), _) => delta_text(row.delta),
            (None, ChangeKind::Added | ChangeKind::Removed) => {
                "— (one side not present)".to_owned()
            }
            (None, ChangeKind::Changed) => "unknown".to_owned(),
        };
        let size = match (row.bytes, row.change) {
            (Some(bytes), _) => format!("{bytes} bytes"),
            (None, ChangeKind::Removed) => "not present".to_owned(),
            (None, _) => "unknown".to_owned(),
        };
        out.push_str(&format!(
            "| {} | {} | {delta} | {size} |\n",
            escape(&row.key),
            row.change.label()
        ));
    }
}

/// `fwsight diff --markdown`, and the desktop's Compare export.
#[must_use]
pub fn comparison(result: &DiffResult) -> String {
    let memory = &result.memory;
    let mut out = String::from("# FirmwareSight · Comparison report\n\n");
    out.push_str(&format!(
        "**Base:** {} · SHA-256 {}  \n**Target:** {} · SHA-256 {}\n\n",
        escape(&result.base_artifact.file_name),
        code(&result.base_artifact.sha256),
        escape(&result.target_artifact.file_name),
        code(&result.target_artifact.sha256)
    ));
    out.push_str(&format!(
        "> Nonvolatile / load image: **{}**. Runtime RAM: **{}**. Comparability: **{}**.\n\n",
        delta_text(memory.nonvolatile.delta),
        delta_text(memory.runtime_ram.delta),
        memory.comparability.label()
    ));

    out.push_str(
        "## Memory\n\n| Quantity | Base | Target | Δ | Comparability |\n|---|---:|---:|---:|---|\n",
    );
    for (label, change) in [
        ("Nonvolatile / load image", &memory.nonvolatile),
        ("Runtime RAM", &memory.runtime_ram),
    ] {
        out.push_str(&format!(
            "| {label} | {} | {} | {} | {} |\n",
            side(change.base),
            side(change.target),
            delta_text(change.delta),
            change.comparability.label()
        ));
    }

    let counts = &result.counts;
    out.push_str("\n## What changed\n\n| | Added | Removed | Changed | Unpaired (name repeats) |\n|---|---:|---:|---:|---:|\n");
    out.push_str(&format!(
        "| Sections | {} | {} | {} | {} |\n| Symbols | {} | {} | {} | {} |\n",
        counts.sections_added,
        counts.sections_removed,
        counts.sections_changed,
        counts.sections_ambiguous,
        counts.symbols_added,
        counts.symbols_removed,
        counts.symbols_changed,
        counts.symbols_ambiguous
    ));
    out.push_str(&format!(
        "\nIdentical, so left out: {} section(s), {} symbol(s). A row whose name repeats is never paired, and is never counted as a change.\n",
        result.unchanged.sections, result.unchanged.symbols
    ));

    out.push_str("\n## Evidence\n");
    contributors(
        &mut out,
        "Top section growth",
        &result.top_section_growth(5),
    );
    contributors(
        &mut out,
        "Largest added sections",
        &result.largest_added_sections(5),
    );
    contributors(&mut out, "Top symbol growth", &result.top_symbol_growth(5));
    contributors(
        &mut out,
        "Largest added symbols",
        &result.largest_added_symbols(5),
    );

    if !result.warnings.is_empty() {
        out.push_str("\n## Warnings\n\n");
        for warning in &result.warnings {
            out.push_str(&format!(
                "- {} {}\n",
                code(&warning.code),
                escape(&warning.message)
            ));
        }
    }

    out.push_str("\n## Limits\n\n");
    out.push_str("- A side that does not exist is written as not present, never as 0.\n");
    out.push_str("- Deltas are Core's; this report ranks nothing itself.\n");
    out.push_str(&format!(
        "- Object and library attribution: {}.\n",
        if result.attribution.available {
            "available from both MAPs".to_owned()
        } else {
            escape(&result.attribution.reason)
        }
    ));
    footer(&mut out, "comparison");
    out
}

/// `fwsight gate --markdown`, and the desktop's Release export.
///
/// It reads the portable gate-results projection (`gate:1`), which is what both the CLI's fresh run and
/// the desktop's stored run can produce, so the two write the same document for the same run.
#[must_use]
pub fn gate(results: &GateResultsDto) -> String {
    let ext = &results.extensions;
    let verdict = ext.overall_effective_severity;
    let mut out = String::from("# FirmwareSight · Release Gate report\n\n");
    out.push_str(&format!(
        "**Run:** {} · **Snapshot:** {} · **Policy:** SHA-256 {}  \n**Baseline:** {}\n\n",
        code(&results.run_id),
        code(&results.snapshot_id),
        code(&ext.policy_sha256),
        ext.baseline_snapshot_id
            .as_deref()
            .map_or_else(|| "none (no comparison in this run)".to_owned(), code)
    ));
    let count = |state: &str| {
        results
            .findings
            .iter()
            .filter(|finding| finding.state == state)
            .count()
    };
    let sentence = sentence_from_words(
        verdict,
        results
            .findings
            .iter()
            .map(|finding| (finding.state, finding.effective_severity)),
        count("PASS"),
    );
    out.push_str(&format!(
        "> **{verdict}** — {}\n>\n> FirmwareSight policy readiness: the answer of this project's policy, not a certification and not a permission to release.\n\n",
        escape(&sentence)
    ));

    out.push_str("## Findings by state\n\n| BLOCK | REVIEW | UNKNOWN | PASS | N/A |\n|---:|---:|---:|---:|---:|\n");
    out.push_str(&format!(
        "| {} | {} | {} | {} | {} |\n",
        count("BLOCK"),
        count("REVIEW"),
        count("UNKNOWN"),
        count("PASS"),
        count("N/A")
    ));

    for state in STATE_ORDER {
        let word = state.as_str();
        let findings: Vec<_> = results
            .findings
            .iter()
            .filter(|finding| finding.state == word)
            .collect();
        if findings.is_empty() {
            continue;
        }
        out.push_str(&format!(
            "\n### **{word}** ({})\n\n| Rule | Effective | Summary | Next step |\n|---|---|---|---|\n",
            findings.len()
        ));
        for finding in &findings {
            // An N/A finding's PASS is a schema filler, not a verdict, so it is not shown as one.
            let effective = if state == FindingState::NotApplicable {
                "—".to_owned()
            } else {
                format!("**{}**", finding.effective_severity)
            };
            out.push_str(&format!(
                "| {} | {effective} | {} | {} |\n",
                code(&finding.rule_id),
                escape(&finding.summary),
                finding
                    .remediation
                    .as_deref()
                    .map_or_else(|| "—".to_owned(), escape)
            ));
        }
    }

    out.push_str("\n## Evidence\n\n");
    for finding in &results.findings {
        if finding.evidence_refs.is_empty() {
            continue;
        }
        out.push_str(&format!(
            "- {}: {}\n",
            code(&finding.rule_id),
            finding
                .evidence_refs
                .iter()
                .map(|reference| code(reference))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }

    out.push_str("\n## Limits\n\n");
    out.push_str("- An UNKNOWN is evidence that never arrived, never a pass.\n");
    out.push_str("- An accepted REVIEW stays REVIEW; only the aggregate moves, and only in the desktop record.\n");
    out.push_str(
        "- Git facts describe the workspace FirmwareSight read, not how the artifact was built.\n",
    );
    footer(&mut out, "Release Gate");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_name_cannot_become_markup_or_leave_its_cell() {
        assert_eq!(escape("a|b"), "a\\|b");
        assert_eq!(escape("firmware.elf"), "firmware.elf");
        assert_eq!(escape("[x](http://y)"), "\\[x\\](http://y)");
        assert_eq!(escape("*bold* _it_ ~s~"), "\\*bold\\* \\_it\\_ \\~s\\~");
        assert_eq!(escape("<script>"), "\\<script\\>");
        assert!(!escape("line\nbreak").contains('\n'));
        assert_eq!(code("a`b"), "`a'b`");
    }
}
