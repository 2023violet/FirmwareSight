/// A process-local counter, so no two plans or staging directories in one session share a name. §26 asks for
/// `bundle-<pid>-<counter>` and forbids a random dependency; an atomic counter is the whole of it.
static SEQUENCE: AtomicUsize = AtomicUsize::new(0);

fn next_plan_id() -> String {
    format!(
        "bundle-{}-{}",
        std::process::id(),
        SEQUENCE.fetch_add(1, Ordering::Relaxed) + 1
    )
}

/// The display half of an I/O failure: its kind, never the path it tried. `std::io::Error`'s `Display`
/// quotes the path, and a path has no business in a preview, a release record or a UI error card.
fn io_detail(error: &std::io::Error) -> String {
    format!("a filesystem operation failed ({:?})", error.kind())
}

/// A sibling directory of `parent` that cannot collide with a bundle or with another session's work.
fn sibling(parent: &Path, purpose: &str) -> PathBuf {
    parent.join(format!(
        ".firmwaresight-{purpose}-{}-{}",
        std::process::id(),
        SEQUENCE.fetch_add(1, Ordering::Relaxed)
    ))
}

/// Write the staged tree: the payload in §41's order, then `SHA256SUMS`, then the manifest.
fn write_tree(content: &BundleContent, staging: &Path) -> Result<(), BundleError> {
    std::fs::create_dir_all(staging.join(ARTIFACTS_DIR)).map_err(|error| {
        BundleError::WriteFailed {
            name: ARTIFACTS_DIR.to_owned(),
            detail: io_detail(&error),
        }
    })?;
    for file in &content.files {
        match &file.body {
            Body::Composed(bytes) => write_bytes(staging, &file.path, bytes)?,
            Body::Copied(source) => copy_file(source, staging, &file.path)?,
        }
    }
    write_bytes(staging, SHA256SUMS_NAME, &content.sums)?;
    write_bytes(staging, MANIFEST_DOC_NAME, content.manifest_json.as_bytes())
}

fn bundle_target(staging: &Path, relative: &str) -> PathBuf {
    staging.join(relative.replace('/', std::path::MAIN_SEPARATOR_STR))
}

fn write_bytes(staging: &Path, relative: &str, bytes: &[u8]) -> Result<(), BundleError> {
    let mut file = create_file(staging, relative)?;
    file.write_all(bytes)
        .map_err(|error| BundleError::WriteFailed {
            name: relative.to_owned(),
            detail: io_detail(&error),
        })?;
    sync(file, relative)
}

/// Copy a verified source file into the bundle without rewriting it (§7, §24).
fn copy_file(source: &Path, staging: &Path, relative: &str) -> Result<(), BundleError> {
    let mut reader = std::fs::File::open(source).map_err(|error| BundleError::WriteFailed {
        name: relative.to_owned(),
        detail: io_detail(&error),
    })?;
    let mut file = create_file(staging, relative)?;
    std::io::copy(&mut reader, &mut file).map_err(|error| BundleError::WriteFailed {
        name: relative.to_owned(),
        detail: io_detail(&error),
    })?;
    sync(file, relative)
}

fn create_file(staging: &Path, relative: &str) -> Result<std::fs::File, BundleError> {
    let target = bundle_target(staging, relative);
    if let Some(parent) = target.parent() {
        std::fs::create_dir_all(parent).map_err(|error| BundleError::WriteFailed {
            name: relative.to_owned(),
            detail: io_detail(&error),
        })?;
    }
    std::fs::File::create(&target).map_err(|error| BundleError::WriteFailed {
        name: relative.to_owned(),
        detail: io_detail(&error),
    })
}

/// §31 step 3, "where appropriate or practical": a bundle a stranger verifies on another machine has to be
/// on the disk, not in a process buffer, before its directory is renamed into place. The flush runs on the
/// write handle, because a read-only handle cannot flush a file on Windows.
fn sync(file: std::fs::File, relative: &str) -> Result<(), BundleError> {
    file.sync_all().map_err(|error| BundleError::WriteFailed {
        name: relative.to_owned(),
        detail: io_detail(&error),
    })
}

/// Discard a staging tree this module wrote. Never called on a destination, and never on a directory that
/// was not created here.
fn discard(staging: &Path) {
    let _ = std::fs::remove_dir_all(staging);
}

/// Publish the staged tree, returning the backup directory when an existing bundle was moved aside.
///
/// An absent destination is one rename. An occupied one is reached only with explicit authorization and only
/// after §32's recognition test, and the predecessor is renamed aside rather than deleted, so a failed swap
/// leaves the release owner with exactly the bundle they had.
fn replace_directory(
    staging: &Path,
    destination: &Path,
    overwrite: bool,
    display: &str,
) -> Result<Option<PathBuf>, BundleError> {
    if !destination.exists() {
        rename(staging, destination, display)?;
        return Ok(None);
    }
    if !overwrite {
        // Unreachable through this module's own API — `publish` refuses first. Stated as a refusal rather
        // than a panic, because this is the last function standing between a rename and a person's folder.
        return Err(BundleError::DestinationExists {
            display: display.to_owned(),
        });
    }
    let parent = destination
        .parent()
        .map_or_else(|| PathBuf::from("."), Path::to_path_buf);
    let backup = sibling(&parent, "replaced");
    rename(destination, &backup, display)?;
    if let Err(error) = rename(staging, destination, display) {
        // Roll the predecessor back before anything is reported.
        let restored = rename(&backup, destination, display);
        return Err(match restored {
            Ok(()) => error,
            Err(rollback) => BundleError::WriteFailed {
                name: display.to_owned(),
                detail: format!(
                    "{} The bundle that was moved aside is still in the folder under the name `{}`.",
                    rollback,
                    backup.file_name().map_or_else(
                        || "a sibling name".to_owned(),
                        |name| name.to_string_lossy().to_string()
                    )
                ),
            },
        });
    }
    Ok(Some(backup))
}

fn rename(from: &Path, to: &Path, display: &str) -> Result<(), BundleError> {
    std::fs::rename(from, to).map_err(|error| BundleError::WriteFailed {
        name: display.to_owned(),
        detail: io_detail(&error),
    })
}

// --------------------------------------------------------------------------- recognition (§32)

/// Whether one directory is a bundle a previous FirmwareSight wrote.
///
/// The test is the smallest thing that can be trusted about a directory: a manifest that parses, says
/// version 1, names FirmwareSight as its producer, and carries a release id shaped like one. Anything else is
/// somebody else's folder, and §31 forbids replacing it because a flag was passed.
///
/// # Errors
///
/// [`BundleError::WriteFailed`] when a manifest is present but cannot be read at all, which is a filesystem
/// problem rather than the "not a bundle" answer `false` means.
pub fn is_recognizable_bundle(root: &Path) -> Result<bool, BundleError> {
    let manifest = root.join(MANIFEST_DOC_NAME);
    if !manifest.is_file() {
        return Ok(false);
    }
    let text = std::fs::read_to_string(&manifest).map_err(|error| BundleError::WriteFailed {
        name: MANIFEST_DOC_NAME.to_owned(),
        detail: io_detail(&error),
    })?;
    let Ok(value) = serde_json::from_str::<serde_json::Value>(&text) else {
        return Ok(false);
    };
    let version = value
        .get("schema_version")
        .and_then(serde_json::Value::as_i64)
        .unwrap_or_default();
    let product = value
        .pointer("/generated_by/product")
        .and_then(serde_json::Value::as_str)
        .unwrap_or_default();
    let id = value
        .pointer("/release/id")
        .and_then(serde_json::Value::as_str)
        .unwrap_or_default();
    Ok(version == 1 && product == "FirmwareSight" && ReleaseId::parse(id).is_ok())
}

// --------------------------------------------------------------------------- verification (§44)

/// Verify a bundle from its own bytes, with no project, no database and no FirmwareSight state (§45).
///
/// This is the engine §44 asks for, used three times: on the staged tree before publication, on the published
/// directory after it, and on a bundle that has been copied somewhere else entirely. It proves the bytes match
/// the two lists and that the lists describe the release they name — an integrity and consistency statement
/// about the bundle as written, and nothing about who wrote it (§62).
///
/// # Errors
///
/// [`BundleError::VerificationFailed`] for anything that makes the bundle not what this build writes, and
/// [`BundleError::WriteFailed`] for a file the bundle should hold and the filesystem will not hand over.
pub fn verify_bundle(root: &Path) -> Result<BundleVerification, BundleError> {
    let files = listed_files(root)?;
    let names: Vec<&str> = files.iter().map(|(name, _)| name.as_str()).collect();

    for required in REQUIRED_BUNDLE_FILES {
        if !names.contains(&required) {
            return Err(fail(format!("`{required}` is not in the bundle")));
        }
    }
    if !names
        .iter()
        .any(|name| name.starts_with(&format!("{ARTIFACTS_DIR}/")))
    {
        return Err(fail(
            "the bundle ships no file under `artifacts/`".to_owned(),
        ));
    }
    for name in &names {
        if !is_safe_bundle_relative_path(name) {
            return Err(fail(format!("`{name}` is not a safe bundle-relative path")));
        }
        let allowed = REQUIRED_BUNDLE_FILES
            .iter()
            .chain(OPTIONAL_BUNDLE_FILES.iter())
            .any(|known| known == name)
            || name.starts_with(&format!("{ARTIFACTS_DIR}/"));
        if !allowed {
            return Err(fail(format!(
                "`{name}` is not a file this bundle layout writes"
            )));
        }
    }
    // Two names that differ only in case are one file to a Windows reader, and a bundle read on whichever
    // host did not write it is half a bundle.
    let mut folded: Vec<String> = names.iter().map(|name| name.to_lowercase()).collect();
    let counted = folded.len();
    folded.sort();
    folded.dedup();
    if folded.len() != counted {
        return Err(fail(
            "two bundle paths name the same file on a case-insensitive filesystem".to_owned(),
        ));
    }

    let manifest = read_json(root, MANIFEST_DOC_NAME)?;
    check_document_contract(MANIFEST_DOC_NAME, &manifest)?;
    let sums = read_text(root, SHA256SUMS_NAME)?;
    let indexed = manifest_file_list(&manifest)?;

    // §21's format, then §44's byte check: every listed digest is the digest of the bytes that are there.
    let mut listed: Vec<(String, String)> = Vec::new();
    for line in sums.split('\n').filter(|line| !line.is_empty()) {
        let Some((digest, path)) = line.split_once("  ") else {
            return Err(fail(format!(
                "`SHA256SUMS` carries a line that is not `<digest>  <path>`: {line}"
            )));
        };
        Sha256::parse(digest).map_err(|_| {
            fail(format!(
                "`SHA256SUMS` carries a digest that is not 64 lowercase hex: {digest}"
            ))
        })?;
        if path.is_empty() || !is_safe_bundle_relative_path(path) {
            return Err(fail(format!("`SHA256SUMS` names `{path}`")));
        }
        listed.push((path.to_owned(), digest.to_owned()));
    }
    for excluded in SUMS_EXCLUDED_NAMES {
        if listed.iter().any(|(path, _)| path == excluded) {
            return Err(fail(format!(
                "`SHA256SUMS` lists `{excluded}`, which it cannot hash without a fixed point"
            )));
        }
    }
    for (path, digest) in &listed {
        let actual = digest_of(&read_bytes(root, path)?);
        if &actual != digest {
            return Err(fail(format!(
                "`{path}` hashes to {actual}, not the {digest} `SHA256SUMS` records"
            )));
        }
    }
    let listed_paths: Vec<String> = listed.iter().map(|(path, _)| path.clone()).collect();
    if !ordered_by_bundle_path(&listed_paths) {
        return Err(fail(
            "`SHA256SUMS` is not in the order this build sorts it into".to_owned(),
        ));
    }

    // The manifest's own list, checked the same way, covering everything the bundle holds — `SHA256SUMS`
    // included, itself excluded (§20).
    let mut manifest_paths: Vec<String> = Vec::new();
    for (path, digest, size) in &indexed {
        if path == MANIFEST_DOC_NAME {
            return Err(fail(
                "`release-manifest.json` indexes itself, which is the faked self-hash §20 refuses"
                    .to_owned(),
            ));
        }
        let bytes = read_bytes(root, path).map_err(|_| {
            fail(format!(
                "the manifest indexes `{path}`, which is not in the bundle"
            ))
        })?;
        if bytes.len() as u64 != *size {
            return Err(fail(format!(
                "`{path}` is {} bytes and the manifest says {size}",
                bytes.len()
            )));
        }
        let actual = digest_of(&bytes);
        if &actual != digest {
            return Err(fail(format!(
                "`{path}` hashes to {actual}, not the {digest} the manifest records"
            )));
        }
        manifest_paths.push(path.clone());
    }
    for required in REQUIRED_BUNDLE_FILES
        .iter()
        .filter(|name| **name != MANIFEST_DOC_NAME)
    {
        if !manifest_paths.iter().any(|path| path == required) {
            return Err(fail(format!("the manifest does not index `{required}`")));
        }
    }
    for name in &names {
        if *name != MANIFEST_DOC_NAME && !manifest_paths.iter().any(|path| path == name) {
            return Err(fail(format!(
                "`{name}` is in the bundle but not indexed by the manifest"
            )));
        }
    }
    if !ordered_by_bundle_path(&manifest_paths) {
        return Err(fail(
            "`release-manifest.json` files[] is not in the order this build sorts it into"
                .to_owned(),
        ));
    }

    // §44's five "schema valid" bullets, checked against the contracts compiled into this binary rather
    // than against a `schemas/` directory the reader may not have. The report reaches nothing outside the
    // bundle, and no generated document carries a host path. The copied Release Notes are exempt from the
    // last two checks: they are the release owner's bytes, byte-for-byte (§24), and a URL or a path inside
    // a sentence about the release is their business, not a leak from this engine.
    let analysis = read_json(root, ANALYSIS_DOC_NAME)?;
    let gate = read_json(root, GATE_RESULTS_DOC_NAME)?;
    let reviews = read_json(root, ACCEPTED_REVIEWS_DOC_NAME)?;
    check_document_contract(ANALYSIS_DOC_NAME, &analysis)?;
    check_document_contract(GATE_RESULTS_DOC_NAME, &gate)?;
    check_document_contract(ACCEPTED_REVIEWS_DOC_NAME, &reviews)?;
    if names.contains(&DIFF_DOC_NAME) {
        let diff = read_json(root, DIFF_DOC_NAME)?;
        check_document_contract(DIFF_DOC_NAME, &diff)?;
    }
    let report_html = read_text(root, REPORT_DOC_NAME)?;
    if report_html.contains("<script")
        || report_html.contains("http://")
        || report_html.contains("https://")
        || report_html.contains("@import")
        || report_html.contains("<link")
    {
        return Err(fail(
            "`release-report.html` reaches outside the bundle it sits in".to_owned(),
        ));
    }
    for name in GENERATED_TEXT_DOCUMENTS {
        // `diff.json` and the rest are conditional on the release, so the bundle is asked whether it carries
        // one rather than reading a file that a release with no baseline never wrote.
        if !names.contains(&name) {
            continue;
        }
        if let Some(found) = host_path_in(&read_text(root, name)?) {
            return Err(fail(format!("`{name}` carries a host path: {found}")));
        }
    }
    if host_path_in(&sums).is_some() {
        return Err(fail(
            "`SHA256SUMS` names something that is not a bundle-relative path".to_owned(),
        ));
    }

    // The strongest check the bytes allow: re-derive what the release id is the digest of from the bundle
    // alone, and require it to equal the id the bundle claims (§44).
    let claimed = manifest
        .pointer("/release/id")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| fail("`release-manifest.json` carries no release id".to_owned()))?;
    let reviews_bytes = read_bytes(root, ACCEPTED_REVIEWS_DOC_NAME)?;
    let rebuilt = model_from_documents(&manifest, &analysis, &reviews, &indexed, &reviews_bytes)?;
    let recomputed = ReleaseModel::release_id_from(&acceptance_bound_digest(&rebuilt));
    if recomputed != claimed {
        return Err(fail(format!(
            "the bundle's documents describe release `{recomputed}`, but it claims `{claimed}`"
        )));
    }

    Ok(BundleVerification {
        release_id: claimed.to_owned(),
        file_count: files.len(),
        total_bytes: files.iter().map(|(_, size)| *size).sum(),
        artifact_count: manifest_paths
            .iter()
            .filter(|path| path.starts_with(&format!("{ARTIFACTS_DIR}/")))
            .count(),
        carries_comparison: names.contains(&DIFF_DOC_NAME),
        carries_release_notes: names.contains(&RELEASE_NOTES_NAME),
    })
}

fn fail(detail: String) -> BundleError {
    BundleError::VerificationFailed { detail }
}

/// The two shapes a host path takes in text this engine wrote: a drive prefix (`C:/`, `d:\`) and a
/// POSIX-absolute home, mount or temporary directory. `urn:firmwaresight:…` and `sha256:…` are not drive
/// prefixes, because the character before the colon is not a lone letter.
fn host_path_in(text: &str) -> Option<&'static str> {
    let bytes = text.as_bytes();
    for index in 0..bytes.len().saturating_sub(2) {
        let (first, middle, last) = (bytes[index], bytes[index + 1], bytes[index + 2]);
        if middle != b':' || !matches!(last, b'/' | b'\\') || !first.is_ascii_alphabetic() {
            continue;
        }
        let standalone = index == 0 || !bytes[index - 1].is_ascii_alphanumeric();
        if standalone {
            return Some("a Windows drive path");
        }
    }
    for marker in [
        "/home/",
        "/Users/",
        "/mnt/",
        "/private/var/",
        "/tmp/",
        "/var/folders/",
    ] {
        if text.contains(marker) {
            return Some("an absolute POSIX path");
        }
    }
    None
}

/// Every file in the tree, bundle-relative and with its size, in Core's single ordering.
fn listed_files(root: &Path) -> Result<Vec<(String, u64)>, BundleError> {
    let mut out = Vec::new();
    let mut stack = vec![(root.to_path_buf(), String::new())];
    while let Some((directory, prefix)) = stack.pop() {
        let entries = std::fs::read_dir(&directory).map_err(|error| BundleError::WriteFailed {
            name: if prefix.is_empty() {
                ".".to_owned()
            } else {
                prefix.clone()
            },
            detail: io_detail(&error),
        })?;
        for entry in entries {
            let entry = entry.map_err(|error| BundleError::WriteFailed {
                name: prefix.clone(),
                detail: io_detail(&error),
            })?;
            let name = entry.file_name().to_string_lossy().to_string();
            let relative = if prefix.is_empty() {
                name.clone()
            } else {
                format!("{prefix}/{name}")
            };
            // `symlink_metadata`, not `DirEntry::file_type`: the last one follows the link, so a symlink to
            // a directory outside the bundle would be walked instead of refused.
            let metadata = std::fs::symlink_metadata(entry.path()).map_err(|error| {
                BundleError::WriteFailed {
                    name: relative.clone(),
                    detail: io_detail(&error),
                }
            })?;
            if metadata.file_type().is_symlink() {
                return Err(fail(format!(
                    "`{relative}` is a symlink, which no bundle writes"
                )));
            }
            if metadata.is_dir() {
                stack.push((entry.path(), relative));
                continue;
            }
            if !metadata.is_file() {
                return Err(fail(format!(
                    "`{relative}` is neither a file nor a directory"
                )));
            }
            out.push((relative, metadata.len()));
        }
    }
    out.sort_by(|left, right| bundle_path_order(&left.0, &right.0));
    Ok(out)
}

fn read_bytes(root: &Path, relative: &str) -> Result<Vec<u8>, BundleError> {
    std::fs::read(bundle_target(root, relative)).map_err(|error| BundleError::WriteFailed {
        name: relative.to_owned(),
        detail: io_detail(&error),
    })
}

fn read_text(root: &Path, relative: &str) -> Result<String, BundleError> {
    let bytes = read_bytes(root, relative)?;
    String::from_utf8(bytes).map_err(|_| {
        fail(format!(
            "`{relative}` is not UTF-8, so no reader can open it as text"
        ))
    })
}

fn read_json(root: &Path, relative: &str) -> Result<serde_json::Value, BundleError> {
    let text = read_text(root, relative)?;
    serde_json::from_str(&text).map_err(|error| {
        fail(format!(
            "`{relative}` does not parse as one JSON document: {error}"
        ))
    })
}

fn digest_of(bytes: &[u8]) -> String {
    fingerprint::sha256_hex(bytes)
}

/// One `files[]` entry of the manifest, as the verifier needs it.
type ManifestEntry = (String, String, u64);

fn manifest_file_list(value: &serde_json::Value) -> Result<Vec<ManifestEntry>, BundleError> {
    let entries = value
        .get("files")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| fail("`release-manifest.json` carries no `files` array".to_owned()))?;
    let mut out = Vec::with_capacity(entries.len());
    for entry in entries {
        let path = entry
            .get("path")
            .and_then(serde_json::Value::as_str)
            .ok_or_else(|| fail("a manifest `files` entry names no path".to_owned()))?;
        let digest = entry
            .get("sha256")
            .and_then(serde_json::Value::as_str)
            .ok_or_else(|| fail(format!("`{path}` is indexed with no digest")))?;
        let size = entry
            .get("size")
            .and_then(serde_json::Value::as_u64)
            .ok_or_else(|| fail(format!("`{path}` is indexed with no size")))?;
        Sha256::parse(digest).map_err(|_| {
            fail(format!(
                "`{path}` is indexed with a digest that is not lowercase hex"
            ))
        })?;
        out.push((path.to_owned(), digest.to_owned(), size));
    }
    Ok(out)
}

fn ordered_by_bundle_path(paths: &[String]) -> bool {
    paths
        .windows(2)
        .all(|pair| bundle_path_order(&pair[0], &pair[1]) != std::cmp::Ordering::Greater)
}

/// The key one document spells its contract major under.
///
/// `analysis:1` (§14) and `diff:1` (§16) are camelCase; `gate-results:1`, `accepted-reviews:1` and
/// `release-manifest:1` are snake_case, and each keeps whichever spelling it was published with, because
/// re-spelling a frozen key is a semantics change that needs a major version (`04_TECH/26`). The table is
/// here rather than in a schema file because §45 makes a relocated bundle verifiable from its own bytes, and
/// a shipped binary has no `schemas/` directory to read. A verifier that assumed one spelling would refuse
/// every analysis document this build itself writes.
fn schema_version_key(document: &str) -> &'static str {
    if document == ANALYSIS_DOC_NAME || document == DIFF_DOC_NAME {
        "schemaVersion"
    } else {
        "schema_version"
    }
}

fn check_schema_identity(value: &serde_json::Value, name: &str) -> Result<(), BundleError> {
    let key = schema_version_key(name);
    let version = value
        .get(key)
        .and_then(serde_json::Value::as_u64)
        .ok_or_else(|| fail(format!("`{name}` carries no `{key}`")))?;
    if version != 1 {
        return Err(fail(format!(
            "`{name}` is major {version}, and this build reads major 1"
        )));
    }
    Ok(())
}

/// How many contract violations one refusal quotes.
///
/// A tampered `symbols` array can fail the same subschema on every row, and a message that recites all of
/// them buries the point. The count is always stated, so a reader knows whether they are looking at the
/// whole of the damage or the first eight of it.
const QUOTED_FAILURES: usize = 8;

/// Check one bundle document against the portable contract its name selects (§44).
///
/// The identity check runs first on purpose. A bundle written under a different major is one clear refusal
/// — "this build reads major 1" — while validating it against the contract this build carries would produce a
/// page of keyword failures for keys that document was never written under, and a page of noise reads like
/// corruption when the real answer is a version mismatch.
///
/// A document that carries major 1 and still fails is what §44 calls a bundle that is not valid: something in
/// it is not the shape this build composes, and every failure is reported with the JSON pointer it was found
/// at so the reader can locate it without reopening the project.
fn check_document_contract(name: &str, value: &serde_json::Value) -> Result<(), BundleError> {
    check_schema_identity(value, name)?;
    let failures =
        schemas::validate(name, value).map_err(|reason| fail(format!("`{name}`: {reason}")))?;
    if failures.is_empty() {
        return Ok(());
    }
    let quoted = failures
        .iter()
        .take(QUOTED_FAILURES)
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join("; ");
    let remainder = if failures.len() > QUOTED_FAILURES {
        format!(", and {} more", failures.len() - QUOTED_FAILURES)
    } else {
        String::new()
    };
    Err(fail(format!(
        "`{name}` does not satisfy the contract it declares: {quoted}{remainder}"
    )))
}

/// Rebuild the semantic inputs from the bundle's own documents, so a release id is checked against the bytes
/// rather than against the plan that produced them.
///
/// Every field comes out of a file: the manifest for the identity, version source and workspace facts, the
/// analysis document for which kind of artifact each shipped leaf is, the file list for the digests, and the
/// acceptance document's own bytes for the digest that binds them.
fn model_from_documents(
    manifest: &serde_json::Value,
    analysis: &serde_json::Value,
    reviews: &serde_json::Value,
    indexed: &[ManifestEntry],
    reviews_bytes: &[u8],
) -> Result<ReleaseModel, BundleError> {
    let field = |pointer: &str| {
        manifest
            .pointer(pointer)
            .and_then(serde_json::Value::as_str)
            .map(str::to_owned)
    };
    let required = |pointer: &str| {
        field(pointer).ok_or_else(|| {
            fail(format!(
                "`release-manifest.json` carries no value at `{pointer}`"
            ))
        })
    };
    let version_source = match field("/extensions/release_version_source").as_deref() {
        Some("release.expected_version") => ReleaseVersionSource::ExpectedVersion,
        Some("git_tag.capture") => ReleaseVersionSource::GitTagCapture,
        other => {
            return Err(fail(format!(
                "`release_version_source` is {other:?}, and a release version comes from one of exactly \
                 two places"
            )));
        }
    };
    // §8 again, this time from the reader's side: a bundle that aggregates to anything but PASS is not a
    // release, whatever its manifest claims.
    let disposition = reviews
        .pointer("/extensions/overall_effective_severity")
        .and_then(serde_json::Value::as_str)
        .unwrap_or_default();
    if disposition != EffectiveSeverity::Pass.as_str() {
        return Err(fail(format!(
            "`accepted-reviews.json` aggregates to {disposition}, and only a PASS disposition is a release"
        )));
    }

    // The kind words live in `analysis.json`, keyed by the leaf each shipped file carries in this bundle.
    let mut kinds: Vec<(String, ArtifactKind)> = Vec::new();
    if let Some(rows) = analysis
        .get("artifacts")
        .and_then(serde_json::Value::as_array)
    {
        for row in rows {
            let name = row.get("fileName").and_then(serde_json::Value::as_str);
            let kind = row.get("kind").and_then(serde_json::Value::as_str);
            if let (Some(name), Some(word)) = (name, kind)
                && let Some(parsed) = ArtifactKind::from_word(word)
            {
                kinds.push((name.to_owned(), parsed));
            }
        }
    }
    let artifacts = indexed
        .iter()
        .filter_map(|(path, digest, size)| {
            path.strip_prefix(&format!("{ARTIFACTS_DIR}/"))
                .map(|leaf| (leaf, digest, size))
        })
        .map(|(leaf, digest, size)| {
            let kind = kinds
                .iter()
                .find(|(name, _)| name == leaf)
                .map(|(_, kind)| *kind)
                .ok_or_else(|| {
                    fail(format!(
                        "`{ARTIFACTS_DIR}/{leaf}` ships, and no document says what kind of artifact it is"
                    ))
                })?;
            Ok(ReleaseArtifact {
                kind,
                file_name: leaf.to_owned(),
                sha256: Sha256::parse(digest).expect("the manifest list was parsed above"),
                byte_size: *size,
            })
        })
        .collect::<Result<Vec<_>, BundleError>>()?;

    let notes = indexed
        .iter()
        .find(|(path, _, _)| path == RELEASE_NOTES_NAME)
        .map(|(_, digest, _)| digest.clone());
    let declared = field("/release/notes");
    let release_notes = match (declared, notes) {
        (Some(_), None) | (None, Some(_)) => {
            return Err(fail(
                "`release.notes` and the bundle's `release-notes.md` disagree about whether the release \
                 has notes"
                    .to_owned(),
            ));
        }
        (Some(name), Some(digest)) => Some(ReleaseNotesDigest {
            bundle_name: name,
            sha256: Sha256::parse(&digest).expect("the manifest list was parsed above"),
        }),
        (None, None) => None,
    };

    let model = ReleaseModel {
        snapshot_id: required("/build/snapshot_id")?,
        baseline_snapshot_id: field("/extensions/baseline_snapshot_id"),
        gate_run_id: required("/extensions/gate_run_id")?,
        disposition: EffectiveSeverity::Pass,
        version: ReleaseVersion::parse(&required("/release/version")?)
            .map_err(BundleError::Release)?,
        version_source,
        acceptances_sha256: Sha256::parse(&digest_of(reviews_bytes))
            .expect("a digest this module computed parses"),
        artifacts,
        release_notes,
        workspace_git: WorkspaceGit {
            head_commit: field("/build/git_commit"),
            exact_tag: field("/build/git_tag"),
            dirty: manifest
                .pointer("/build/git_dirty")
                .and_then(serde_json::Value::as_bool),
        },
        schema_majors: SchemaMajors::CURRENT,
        fwsight_version: required("/generated_by/version")?,
    };
    model.validated().map_err(BundleError::Release)
}

