/// One file the plan will write.
#[derive(Debug, Clone)]
struct StagedFile {
    /// Bundle-relative and `/`-separated.
    path: String,
    role: FileRole,
    body: Body,
    sha256: String,
    byte_size: u64,
}

/// Either bytes this module composed, or a verified source file copied without being opened again in a way
/// that could change them. §24's notes copy and §22's artifacts are byte-for-byte by definition.
#[derive(Debug, Clone)]
enum Body {
    Composed(Vec<u8>),
    Copied(PathBuf),
}

/// Every byte of the bundle, in §41's order, plus the two indexes appended after the payload.
#[derive(Debug, Clone)]
struct BundleContent {
    model: ReleaseModel,
    release_id: String,
    policy_sha256: String,
    directory_name: String,
    files: Vec<StagedFile>,
    /// The configuration findings the release was prepared under, carried into the preview (§27). They name
    /// policy keys rather than files, so none of them can be a host path.
    warnings: Vec<String>,
    sums: Vec<u8>,
    sums_sha256: String,
    manifest_json: String,
    manifest_sha256: String,
}

impl BundleContent {
    fn new(
        model: &ReleaseModel,
        release_id: String,
        policy_sha256: String,
        project_name: &str,
        warnings: Vec<String>,
    ) -> Self {
        // §29's proposed name, built from facts rather than from a folder the caller chose.
        let directory_name = format!(
            "{}-{}-{}",
            sanitize_leaf_name(project_name),
            model.version.as_str(),
            ReleaseId::parse(&release_id)
                .expect("the release id was assembled by this module")
                .short_hex()
        );
        Self {
            model: model.clone(),
            release_id,
            policy_sha256,
            directory_name,
            warnings,
            files: Vec::new(),
            sums: Vec::new(),
            sums_sha256: String::new(),
            manifest_json: String::new(),
            manifest_sha256: String::new(),
        }
    }

    fn push_generated(&mut self, path: &str, role: FileRole, text: String) {
        let byte_size = text.len() as u64;
        let sha256 = fingerprint::sha256_hex(text.as_bytes());
        self.files.push(StagedFile {
            path: path.to_owned(),
            role,
            body: Body::Composed(text.into_bytes()),
            sha256,
            byte_size,
        });
    }

    fn push_copied(
        &mut self,
        path: &str,
        role: FileRole,
        source: PathBuf,
        sha256: String,
        byte_size: u64,
    ) {
        self.files.push(StagedFile {
            path: path.to_owned(),
            role,
            body: Body::Copied(source),
            sha256,
            byte_size,
        });
    }

    /// The `files[]` shape the manifest and `SHA256SUMS` are both built from, in Core's single ordering.
    fn index_entries(&self) -> Vec<ManifestFileDto> {
        let mut entries: Vec<ManifestFileDto> = self
            .files
            .iter()
            .map(|file| ManifestFileDto::new(&file.path, &file.sha256, file.byte_size))
            .collect();
        entries.sort_by(|left, right| bundle_path_order(&left.path, &right.path));
        entries
    }

    fn preview(&self, plan_id: String) -> BundlePreview {
        let mut files: Vec<PlannedFile> = self
            .files
            .iter()
            .map(|file| PlannedFile {
                path: file.path.clone(),
                role: file.role,
                byte_size: file.byte_size,
                sha256: file.sha256.clone(),
            })
            .collect();
        files.push(PlannedFile {
            path: SHA256SUMS_NAME.to_owned(),
            role: FileRole::ChecksumIndex,
            byte_size: self.sums.len() as u64,
            sha256: self.sums_sha256.clone(),
        });
        files.push(PlannedFile {
            path: MANIFEST_DOC_NAME.to_owned(),
            role: FileRole::Manifest,
            byte_size: self.manifest_json.len() as u64,
            sha256: self.manifest_sha256.clone(),
        });
        files.sort_by(|left, right| bundle_path_order(&left.path, &right.path));
        BundlePreview {
            plan_id,
            release_id: self.release_id.clone(),
            release_version: self.model.version.as_str().to_owned(),
            snapshot_id: self.model.snapshot_id.clone(),
            baseline_snapshot_id: self.model.baseline_snapshot_id.clone(),
            gate_run_id: self.model.gate_run_id.clone(),
            disposition: self.model.disposition.as_str(),
            files,
            warnings: self.warnings.clone(),
        }
    }
}

