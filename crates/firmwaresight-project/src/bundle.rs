//! Staging a Release Bundle: the one publication engine the CLI and the desktop share.
//!
//! The placement is deliberate. Prompt §36 puts portable *content* in `firmwaresight-report` and bundle
//! *publication* in the application layer, while §35 requires the CLI and the desktop to run the same
//! staging/swap engine and §65 forbids a sixth crate. A crate that already reads config, Release Notes and
//! Git, and already owns `sha2`, is the only place that satisfies all three at once — the arrangement is
//! recorded in `.ai/DECISIONS.md` as "Two crates share the work". What follows from it is the edge this
//! module keeps: `report` composes bytes, this module verifies, stages, publishes and re-reads them, and
//! neither decides what a Gate state means. Core does, through the P3 adapter in [`crate::evidence`].
//!
//! ```text
//! facts from the app ─▶ observe() ─▶ BundlePlan ─▶ publish() ─▶ <bundle-root>/
//!   snapshot, git,      §9 §8 §11    §27 preview    §28 §31      §7 layout
//!   config, reviews     §22 §23 §24  §42 bytes      §30 §32      §44 verified
//! ```
//!
//! Three properties hold the design together:
//!
//! 1. **A bundle is a verdict output, not an export of whatever is on screen.** Preparation re-observes the
//!    project, rebuilds the Gate context through the same adapter that produced the stored run, and refuses
//!    unless the run id it recomputes equals the run that was selected (§9). A stale `PASS` over a newly
//!    dirty workspace therefore produces no bundle.
//! 2. **The plan is the payload.** [`prepare`] composes every generated byte, hashes it, and keeps the
//!    result; [`BundlePlan::publish`] writes those same bytes and never re-renders anything. That is what
//!    makes §41's ordering enforceable instead of aspirational: the report is composed before `SHA256SUMS`,
//!    `SHA256SUMS` before the manifest, and nothing is regenerated after the manifest exists.
//! 3. **Nothing destructive happens to a directory this engine did not write.** An existing destination is
//!    refused (§30); with explicit authorization it is first required to be a recognizable FirmwareSight
//!    bundle (§32), then renamed aside, then replaced, then discarded — and a failed swap puts the backup
//!    back. An arbitrary user directory is never recursively deleted, `overwrite` notwithstanding.
//!
//! Host paths stop at this boundary in both directions. A source path enters as an input; every value that
//! leaves — preview, plan, verification, error text — names a bundle-relative path or a display leaf
//! (`AGENTS.md` 7, prompt §27, §29).

