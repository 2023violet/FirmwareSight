/// Every way publication refuses, with the §51 code a UI can show and a report can quote.
///
/// Each message states what happened and what the release owner does next, because the commonest of these is
/// not a bug: it is a workspace that moved after the Gate ran.
#[derive(Debug, thiserror::Error)]
pub enum BundleError {
    /// The disposition after the accepted reviews is not `PASS`, no version could be resolved, or nothing
    /// was selected to ship (§8, §11). Core owns those refusals, so its error is carried through rather than
    /// re-described here — and `ERR-BUNDLE-6101`/`6110` are named in one place.
    #[error(transparent)]
    Release(#[from] ReleaseError),

    /// The assembled index refused the assembled content: the bundle as computed is not a bundle this build
    /// would write, so nothing was written.
    #[error(transparent)]
    Index(#[from] ManifestError),

    /// The run that was selected is not the run this context produces (§9).
    #[error(
        "the Gate run selected is `{selected}` but the current project context recomputes to \
         `{recomputed}`: the workspace, configuration or Release Notes moved after that run was recorded"
    )]
    GateContextChanged {
        selected: String,
        recomputed: String,
    },

    /// A source file is missing, not regular, unreadable, or no longer the bytes the snapshot hashed (§22).
    #[error("the source of `{name}` is not the bytes the build recorded: {detail}")]
    SourceArtifactChanged { name: String, detail: String },

    /// The Release Notes are not the bytes the recomputed context observed (§24).
    #[error("the Release Notes are not the bytes the Gate observed: {detail}")]
    ReleaseNotesChanged { detail: String },

    /// Something the preview was built from changed between preview and export (§28).
    #[error("the bundle plan is stale: {detail}")]
    PlanStale { detail: String },

    /// The destination directory already exists and this export was not authorized to replace it (§30).
    #[error(
        "`{display}` already exists in the chosen folder, and exporting would replace the bundle that is \
         there"
    )]
    DestinationExists { display: String },

    /// Replacement was authorized, but the existing directory is not a recognizable FirmwareSight bundle,
    /// so it is somebody else's data (§31, §32).
    #[error("refused to replace `{display}`: {detail}")]
    UnsafeDestination { display: String, detail: String },

    /// A write, flush or rename failed. The staged tree was discarded and the destination is untouched.
    #[error("could not write `{name}` into the bundle: {detail}")]
    WriteFailed { name: String, detail: String },

    /// What was written does not match what the bundle records about itself (§31 step 10, §44).
    #[error("the bundle did not verify: {detail}")]
    VerificationFailed { detail: String },

    /// A structural expectation of this module was violated, which is a bug rather than user input.
    #[error("internal invariant violated: {detail}")]
    Internal { detail: String },
}

impl BundleError {
    /// The stable diagnostics code.
    #[must_use]
    pub fn code(&self) -> &'static str {
        match self {
            Self::Release(error) => error.code(),
            Self::Index(_) | Self::VerificationFailed { .. } => "ERR-BUNDLE-6109",
            Self::GateContextChanged { .. } => "ERR-BUNDLE-6102",
            Self::SourceArtifactChanged { .. } => "ERR-BUNDLE-6103",
            Self::ReleaseNotesChanged { .. } => "ERR-BUNDLE-6104",
            Self::PlanStale { .. } => "ERR-BUNDLE-6105",
            Self::DestinationExists { .. } => "ERR-BUNDLE-6106",
            Self::UnsafeDestination { .. } => "ERR-BUNDLE-6107",
            Self::WriteFailed { .. } => "ERR-BUNDLE-6108",
            Self::Internal { .. } => "ERR-INTERNAL-9004",
        }
    }

    /// What the release owner can do next. §51 forbids a stack trace in a UI, so this sentence, shown under
    /// the error, is the whole of the remediation surface.
    #[must_use]
    pub fn remediation(&self) -> &'static str {
        match self {
            Self::Release(ReleaseError::VersionUnavailable { .. }) => {
                "configure a version policy and an expected version, or tag the release so the pattern \
                 captures one, then run the Gate again"
            }
            Self::Release(_) => {
                "run the Gate again and resolve what it reports: a bundle is written only for a PASS \
                 disposition"
            }
            Self::Index(_) | Self::VerificationFailed { .. } => {
                "keep whatever was written, and report the release id and the Gate run id: a bundle that \
                 does not verify against itself is evidence, not something to retry over the top of"
            }
            Self::GateContextChanged { .. } => "run the Gate again and review the new result",
            Self::SourceArtifactChanged { .. } => {
                "re-analyze the intended artifact, or restore the exact bytes. A snapshot's hash is never \
                 updated to match a file that moved"
            }
            Self::ReleaseNotesChanged { .. } => {
                "restore the notes the Gate read, or run the Gate again over the new ones"
            }
            Self::PlanStale { .. } => "prepare the bundle again",
            Self::DestinationExists { .. } => {
                "choose another folder, or confirm the replacement explicitly"
            }
            Self::UnsafeDestination { .. } => {
                "choose another folder: only a directory FirmwareSight wrote as a release bundle is \
                 eligible for replacement"
            }
            Self::WriteFailed { .. } => {
                "check the free space and permissions of the chosen folder, then prepare the bundle again"
            }
            Self::Internal { .. } => {
                "report the release id and the Gate run id; no bundle was written"
            }
        }
    }
}

