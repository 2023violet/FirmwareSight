/// Prepare a bundle: §26's steps 1 through 14, ending in a preview and an opaque plan id.
///
/// Nothing is written here. A plan holds the exact bytes it would write, so the preview a release owner
/// authorized and the bundle that appears in their folder cannot turn out to be two different documents.
///
/// # Errors
///
/// Any [`BundleError`] except the destination-dependent ones: preparation has not looked at a folder yet.
pub fn prepare(request: &BundleRequest<'_>) -> Result<BundlePlan, BundleError> {
    let observed = observe(request)?;
    Ok(BundlePlan {
        preview: observed.content.preview(next_plan_id()),
        content: observed.content,
        checks: observed.checks,
    })
}

/// What §26's steps read and check, before any plan id or destination exists.
struct Observation {
    content: BundleContent,
    checks: InputChecks,
}

/// The re-checkable identity of a plan's inputs (§28).
///
/// Source paths appear here and nowhere else: they are the caller's own strings, kept private so they cannot
/// reach a preview, a portable document, or even an error message.
#[derive(Debug, Clone, PartialEq, Eq)]
struct InputChecks {
    run_id: String,
    policy_sha256: String,
    acceptances_sha256: String,
    /// `(source path as recorded, digest, size)` for every shipped row, in snapshot order.
    sources: Vec<(String, String, u64)>,
    /// `(project-relative notes path, digest, size)`, when the policy asked for notes at all.
    notes: Option<(String, String, u64)>,
}

impl InputChecks {
    /// Report the first thing that moved, naming it in the terms §28 lists. A source or notes change keeps
    /// its own §51 code, because its remediation is about the file rather than about the plan.
    fn compare_with(&self, now: &Self) -> Result<(), BundleError> {
        if self.sources != now.sources {
            return Err(BundleError::SourceArtifactChanged {
                name: changed_leaf(&self.sources, &now.sources),
                detail: "the file was read again at export and is no longer the bytes the preview hashed"
                    .to_owned(),
            });
        }
        if self.notes != now.notes {
            return Err(BundleError::ReleaseNotesChanged {
                detail: "the file was read again at export and is no longer the bytes the preview hashed"
                    .to_owned(),
            });
        }
        if self.run_id != now.run_id {
            return Err(stale("Gate run id", &now.run_id));
        }
        if self.policy_sha256 != now.policy_sha256 {
            return Err(stale("policy fingerprint", &now.policy_sha256));
        }
        if self.acceptances_sha256 != now.acceptances_sha256 {
            return Err(stale("acceptance set", &now.acceptances_sha256));
        }
        Ok(())
    }
}

/// §28's one remediation for everything that is not a file: the preview no longer describes the world.
fn stale(label: &str, now: &str) -> BundleError {
    BundleError::PlanStale {
        detail: format!("the {label} changed after the preview: it is now `{now}`"),
    }
}

/// The leaf of the shipped file whose bytes moved, for an error a person reads. Never its path.
fn changed_leaf(earlier: &[(String, String, u64)], now: &[(String, String, u64)]) -> String {
    earlier
        .iter()
        .zip(now)
        .find(|(was, is)| was != is)
        .map_or_else(
            || "a shipped artifact".to_owned(),
            |(was, _)| sanitize_leaf_name(&was.0),
        )
}

fn observe(request: &BundleRequest<'_>) -> Result<Observation, BundleError> {
    let policy = request.project.policy.clone();
    let target = SnapshotFacts::from_snapshot(request.snapshot);

    // §9's reuse rule: the context is assembled by the same adapter the Gate ran on, with the notes observed
    // by the same call, so a recomputed run id is comparable with a stored one rather than merely similar.
    let notes = policy.require_release_notes.then(|| {
        evidence::observe_release_notes(&request.project.root, &policy.release_notes_path)
    });
    let growth = match request.comparison {
        Some(diff) => {
            if diff.target_snapshot_id != target.snapshot_id {
                return Err(BundleError::Internal {
                    detail: format!(
                        "the comparison names target `{}` while the shipped snapshot is `{}`",
                        diff.target_snapshot_id, target.snapshot_id
                    ),
                });
            }
            evidence::growth_facts(diff)
        }
        None => GateGrowthFacts::without_baseline(),
    };
    let context = evidence::build_context(&evidence::GateRunRequest {
        target: &target,
        growth,
        git: request.git,
        policy: policy.clone(),
        release_notes: notes.clone(),
    });

    let run_id = fingerprint::run_id(&context);
    if let Some(selected) = request.selected_run_id
        && selected != run_id
    {
        return Err(BundleError::GateContextChanged {
            selected: selected.to_owned(),
            recomputed: run_id,
        });
    }
    let evaluation = context.evaluate(&run_id);

    // §10: an acceptance is part of this run's record or it is nothing. The finding has to exist in the
    // recomputed run and has to have been a REVIEW, which is also what keeps an evidence gap unpackageable.
    for acceptance in request.acceptances {
        let finding = evaluation
            .findings
            .iter()
            .find(|candidate| candidate.id == acceptance.finding_id);
        match finding {
            None => {
                return Err(BundleError::Internal {
                    detail: format!(
                        "an acceptance names `{}`, which is not a finding of run `{run_id}`",
                        acceptance.finding_id
                    ),
                });
            }
            Some(found) if found.state != FindingState::Review => {
                return Err(BundleError::Internal {
                    detail: format!(
                        "an acceptance names `{}`, which the run recorded as {}. Only a REVIEW is \
                         acceptable, and an UNKNOWN never becomes one by being signed away",
                        acceptance.finding_id,
                        found.state.as_str()
                    ),
                });
            }
            Some(_) => {}
        }
    }
    let accepted_ids: Vec<String> = request
        .acceptances
        .iter()
        .map(|acceptance| acceptance.finding_id.clone())
        .collect();
    let disposition = evaluation.aggregate_with_acceptances(&accepted_ids);
    // §8 answered before §22: a release that has not earned a bundle is refused on its verdict, so a BLOCK
    // on missing Release Notes reads as the Gate blocking rather than as a file that could not be copied.
    // Core owns the rule; this is the earlier of the two calls to it.
    require_packageable(disposition)?;

    let (version, version_source) = resolve_version(&policy, &context, &evaluation)?;

    // §22 then §23: read and check every source file, then name it safely inside the bundle.
    let shipped = verify_sources(&request.project.root, request.snapshot, &context)?;
    let leaves = bundle_names(&shipped);
    let mut artifacts = shipped
        .iter()
        .zip(&leaves)
        .map(|(row, leaf)| ReleaseArtifact {
            kind: row.kind,
            file_name: leaf.clone(),
            sha256: row.sha256.clone(),
            byte_size: row.byte_size,
        })
        .collect::<Vec<_>>();
    // §52.11: canonical order is a property of the model, and the write order and the manifest both follow
    // it, so pairing a row with a leaf later cannot depend on which directory listing came first.
    artifacts.sort_by(|left, right| {
        ReleaseArtifact::kind_word(left.kind)
            .cmp(ReleaseArtifact::kind_word(right.kind))
            .then_with(|| left.sha256.hex().cmp(right.sha256.hex()))
            .then_with(|| left.byte_size.cmp(&right.byte_size))
            .then_with(|| left.file_name.cmp(&right.file_name))
    });

    // §24: the notes copy is byte-for-byte, identified by the digest the recomputed context already carries.
    let notes_copy = notes.as_ref().map(|fact| match &fact.status {
        GateFileStatus::Present {
            sha256: Some(digest),
        } => {
            let source =
                evidence::join_project_relative(&request.project.root, &policy.release_notes_path);
            std::fs::metadata(&source)
                .map(|metadata| NotesCopy {
                    source,
                    relative: policy.release_notes_path.clone(),
                    sha256: digest.clone(),
                    byte_size: metadata.len(),
                })
                .map_err(|error| BundleError::ReleaseNotesChanged {
                    detail: io_detail(&error),
                })
        }
        GateFileStatus::Present { sha256: None } => Err(BundleError::ReleaseNotesChanged {
            detail:
                "the Gate found the file but read no digest from it, so there is nothing to ship \
                     against"
                    .to_owned(),
        }),
        GateFileStatus::Missing => Err(BundleError::ReleaseNotesChanged {
            detail: format!(
                "`{}` is the configured Release Notes path and nothing is there",
                sanitize_leaf_name(&fact.relative_path)
            ),
        }),
        GateFileStatus::Unreadable { reason } => Err(BundleError::ReleaseNotesChanged {
            detail: format!("`{}`: {reason}", sanitize_leaf_name(&fact.relative_path)),
        }),
    });
    let notes_copy = match notes_copy {
        Some(Ok(copy)) => Some(copy),
        Some(Err(error)) => return Err(error),
        None => None,
    };
    let notes_digest = notes_copy
        .as_ref()
        .map(|copy| {
            Sha256::parse(&copy.sha256).map_err(|_| BundleError::ReleaseNotesChanged {
                detail: "the observed Release Notes digest is not lowercase hex".to_owned(),
            })
        })
        .transpose()?;

    let reviews_document = AcceptedReviewsDto::new(
        &run_id,
        &request
            .acceptances
            .iter()
            .map(|acceptance| AcceptanceDto {
                finding_id: acceptance.finding_id.clone(),
                actor: acceptance.actor.clone(),
                accepted_at: acceptance.accepted_at.clone(),
                reason: acceptance.reason.clone(),
                original_state: ACCEPTANCE_ORIGINAL_STATE,
            })
            .collect::<Vec<_>>(),
        disposition,
    );
    let reviews_json = document_json(&reviews_document);
    let acceptances_sha256 = fingerprint::sha256_hex(reviews_json.as_bytes());

    let model = ReleaseModel {
        snapshot_id: target.snapshot_id.clone(),
        baseline_snapshot_id: request.comparison.map(|diff| diff.base_snapshot_id.clone()),
        gate_run_id: run_id.clone(),
        disposition,
        version,
        version_source,
        acceptances_sha256: Sha256::parse(&acceptances_sha256)
            .expect("a digest of 32 bytes is always 64 lowercase hex"),
        artifacts,
        release_notes: notes_digest.map(|sha256| ReleaseNotesDigest {
            bundle_name: RELEASE_NOTES_NAME.to_owned(),
            sha256,
        }),
        workspace_git: WorkspaceGit {
            head_commit: request.git.facts.head_commit.value().cloned(),
            exact_tag: request.git.facts.exact_tag.value().cloned(),
            dirty: request.git.facts.dirty.value().copied(),
        },
        schema_majors: SchemaMajors::CURRENT,
        fwsight_version: request.fwsight_version.to_owned(),
    }
    .validated()?;
    // §8 is stated once, in Core: `REVIEW` and `BLOCK` both refuse here with `ERR-BUNDLE-6101`.

    // The release id is the digest of the semantic inputs, so it exists before the report prints it and
    // before the manifest names it. Nothing that follows can change an input without changing it.
    let release_id = ReleaseModel::release_id_from(&acceptance_bound_digest(&model));

    let gate_document = GateResultsDto::from_evaluation(
        &evaluation,
        &request.project.policy_sha256,
        request.project.config.schema_version,
    );
    let analysis_document = AnalysisDocumentDto::from_snapshot(request.snapshot, &model.artifacts);
    let comparison_document = request.comparison.map(DiffResultDto::from_diff);

    let mut content = BundleContent::new(
        &model,
        release_id,
        request.project.policy_sha256.clone(),
        &request.project.config.project.name,
        // §27's warnings: the configuration findings the release was prepared under. They name policy keys,
        // never files, so they are the one kind of warning that may cross IPC. What the *build* could not
        // establish travels in `gate-results.json` and `diff.json`, beside the bytes it describes.
        request.project.warnings.clone(),
    );

    // §41's order. Copied files carry the digest of the bytes that were verified; generated documents carry
    // the digest of the bytes composed here and never recomputed again.
    for artifact in &model.artifacts {
        let row = shipped
            .iter()
            .find(|row| row.sha256 == artifact.sha256)
            .expect("the shipped list was built from these rows");
        content.push_copied(
            &format!("{ARTIFACTS_DIR}/{}", artifact.file_name),
            FileRole::ShippedArtifact,
            row.source.clone(),
            artifact.sha256.hex().to_owned(),
            artifact.byte_size,
        );
    }
    content.push_generated(
        ANALYSIS_DOC_NAME,
        FileRole::Analysis,
        document_json(&analysis_document),
    );
    if let Some(diff) = comparison_document.as_ref() {
        content.push_generated(DIFF_DOC_NAME, FileRole::Comparison, document_json(diff));
    }
    content.push_generated(
        GATE_RESULTS_DOC_NAME,
        FileRole::GateResults,
        document_json(&gate_document),
    );
    content.push_generated(
        ACCEPTED_REVIEWS_DOC_NAME,
        FileRole::AcceptedReviews,
        reviews_json,
    );
    if let Some(copy) = &notes_copy {
        content.push_copied(
            RELEASE_NOTES_NAME,
            FileRole::ReleaseNotes,
            copy.source.clone(),
            copy.sha256.clone(),
            copy.byte_size,
        );
    }

    // §7's report is composed from what already exists in the bundle. It prints a digest for every file
    // written before it, and only a name for `SHA256SUMS`, the manifest, and itself.
    let staged = content.index_entries();
    let growth = request.comparison.map(|diff| GrowthRows {
        sections: diff.top_section_growth(REPORT_GROWTH_ROWS),
        symbols: diff.top_symbol_growth(REPORT_GROWTH_ROWS),
    });
    let report = ReleaseBundleReport {
        model: &model,
        release_id: &content.release_id,
        policy_sha256: &content.policy_sha256,
        staged: &staged,
        analysis: &analysis_document,
        compare: comparison_document.as_ref().map(|diff| CompareSummary {
            result: diff,
            top_sections: &growth.as_ref().expect("a comparison carries rows").sections,
            top_symbols: &growth.as_ref().expect("a comparison carries rows").symbols,
        }),
        gate_counts: evaluation.counts,
        gate: &gate_document,
        reviews: &reviews_document,
    };
    content.push_generated(
        REPORT_DOC_NAME,
        FileRole::Report,
        release_render::render_html(&report),
    );

    // Then the two indexes, in that order. After the manifest nothing is regenerated (§41).
    let indexed = content.index_entries();
    let sums = release_render::render_sums(&indexed);
    content.sums_sha256 = fingerprint::sha256_hex(sums.as_bytes());
    content.sums = sums.into_bytes();

    let mut manifest_files = indexed;
    manifest_files.push(ManifestFileDto::new(
        SHA256SUMS_NAME,
        &content.sums_sha256,
        content.sums.len() as u64,
    ));
    let manifest = ReleaseManifestDto::from_parts(
        &model,
        &content.release_id,
        &manifest_files,
        &content.policy_sha256,
    )?;
    content.manifest_json = release_render::render_json(&manifest);
    content.manifest_sha256 = fingerprint::sha256_hex(content.manifest_json.as_bytes());

    let checks = InputChecks {
        run_id,
        policy_sha256: request.project.policy_sha256.clone(),
        acceptances_sha256,
        sources: shipped
            .iter()
            .map(|row| {
                (
                    row.raw_path.clone(),
                    row.sha256.hex().to_owned(),
                    row.byte_size,
                )
            })
            .collect(),
        notes: notes_copy
            .as_ref()
            .map(|copy| (copy.relative.clone(), copy.sha256.clone(), copy.byte_size)),
    };
    Ok(Observation { content, checks })
}

/// §12 in one line: the release id is the digest of the canonical semantic inputs, prefix included.
fn acceptance_bound_digest(model: &ReleaseModel) -> String {
    fingerprint::sha256_hex(model.canonical_release_text().as_bytes())
}

/// The two growth rankings the report prints, taken from Core's selectors.
struct GrowthRows {
    sections: Vec<firmwaresight_core::domain::diff::Contributor>,
    symbols: Vec<firmwaresight_core::domain::diff::Contributor>,
}

/// One verified source row, as §22 requires it to be known before anything is copied.
#[derive(Debug, Clone)]
struct VerifiedRow {
    kind: ArtifactKind,
    sha256: Sha256,
    byte_size: u64,
    /// The path as the snapshot recorded it, for revalidation only.
    raw_path: String,
    source: PathBuf,
}

/// A Release Notes file to copy, as the recomputed context described it (§24).
#[derive(Debug, Clone)]
struct NotesCopy {
    source: PathBuf,
    relative: String,
    sha256: String,
    byte_size: u64,
}

/// Read, hash and check every shipped artifact, in snapshot order (§22, §23).
///
/// The checks run in the prompt's own sequence — stat, regular file, streaming hash, compare hash, compare
/// size — and a failure is a refusal, never an update of the stored digest. The snapshot stays immutable.
fn verify_sources(
    root: &Path,
    snapshot: &BuildSnapshot,
    context: &GateContext,
) -> Result<Vec<VerifiedRow>, BundleError> {
    let mut rows = Vec::new();
    for artifact in snapshot.artifacts() {
        let leaf = sanitize_leaf_name(&artifact.path);
        if !matches!(artifact.kind, ArtifactKind::Elf | ArtifactKind::Map) {
            // §23 ships the ELF and, when supplied, its MAP. A row of another kind is not quietly dropped:
            // a bundle whose manifest omits a file the build recorded is the half-verifiable bundle §44
            // exists to catch.
            return Err(BundleError::Internal {
                detail: format!(
                    "`{leaf}` is a `{}` artifact and this build ships no artifact of that kind",
                    ReleaseArtifact::kind_word(artifact.kind)
                ),
            });
        }
        let path = resolve_source(root, &artifact.path);
        let metadata =
            std::fs::metadata(&path).map_err(|error| BundleError::SourceArtifactChanged {
                name: leaf.clone(),
                detail: if error.kind() == std::io::ErrorKind::NotFound {
                    "the file the build was analyzed from is not there".to_owned()
                } else {
                    io_detail(&error)
                },
            })?;
        if !metadata.is_file() {
            return Err(BundleError::SourceArtifactChanged {
                name: leaf.clone(),
                detail: "the path is not a regular file".to_owned(),
            });
        }
        let digest = fingerprint::file_sha256(&path).map_err(|error| {
            BundleError::SourceArtifactChanged {
                name: leaf.clone(),
                detail: io_detail(&error),
            }
        })?;
        if digest != artifact.sha256.hex() {
            return Err(BundleError::SourceArtifactChanged {
                name: leaf.clone(),
                detail: "its SHA-256 is not the digest the snapshot holds".to_owned(),
            });
        }
        if metadata.len() != artifact.byte_size {
            return Err(BundleError::SourceArtifactChanged {
                name: leaf.clone(),
                detail: format!(
                    "it is {} bytes and the snapshot recorded {}",
                    metadata.len(),
                    artifact.byte_size
                ),
            });
        }
        // The bytes shipped have to be the bytes the Gate judged: a row the assembled context never saw would
        // mean the snapshot and the context came from different builds.
        if !context
            .artifacts
            .iter()
            .any(|fact| fact.kind == artifact.kind && fact.sha256.value() == Some(&digest))
        {
            return Err(BundleError::Internal {
                detail: format!(
                    "`{leaf}` is in the snapshot but not in the Gate context read from it"
                ),
            });
        }
        rows.push(VerifiedRow {
            kind: artifact.kind,
            sha256: artifact.sha256.clone(),
            byte_size: artifact.byte_size,
            raw_path: artifact.path.clone(),
            source: path,
        });
    }
    if rows.is_empty() {
        return Err(BundleError::Release(ReleaseError::NoReleaseArtifacts));
    }
    Ok(rows)
}

/// A snapshot's recorded source path, resolved the one way this module allows: absolute as it was given,
/// relative to the project root. That is the directory the analysis ran from, so a build whose artifact
/// lives elsewhere has to name it absolutely, and anything unresolvable fails closed in
/// [`verify_sources`] rather than shipping a guess.
fn resolve_source(root: &Path, raw: &str) -> PathBuf {
    let path = Path::new(raw);
    if path.is_absolute() {
        return path.to_path_buf();
    }
    evidence::join_project_relative(root, raw)
}

/// The bundle leaves for the verified rows (§23), collision-free even on a case-insensitive filesystem.
///
/// Recognition first — the original leaf, sanitized. Two rows that would land on one name are *both* renamed
/// to Core's content-keyed form, so the pair sorts identically in every bundle and neither file wins by
/// whichever directory entry arrived first.
fn bundle_names(rows: &[VerifiedRow]) -> Vec<String> {
    let base: Vec<String> = rows
        .iter()
        .map(|row| sanitize_leaf_name(&row.raw_path))
        .collect();
    let mut counted: std::collections::BTreeMap<String, usize> = std::collections::BTreeMap::new();
    for name in &base {
        *counted.entry(name.to_lowercase()).or_insert(0) += 1;
    }
    base.iter()
        .zip(rows)
        .map(|(name, row)| {
            if counted[&name.to_lowercase()] > 1 {
                disambiguated_name(row.kind, &row.sha256, name)
            } else {
                name.clone()
            }
        })
        .collect()
}

/// §11's precedence, read off the context the Gate judged rather than from a dialog.
///
/// `release.expected_version` first, but only when the version rule passed — a version the Gate never
/// endorsed is not a release version. Otherwise the `version` capture the exact tag yielded under
/// `[version] pattern`. Never the app version, a file name, or an import timestamp.
fn resolve_version(
    policy: &GatePolicy,
    context: &GateContext,
    evaluation: &GateEvaluation,
) -> Result<(ReleaseVersion, ReleaseVersionSource), BundleError> {
    let endorsed = evaluation
        .finding(GateRuleId::VersionMatchesPolicy)
        .is_some_and(|finding| finding.state == FindingState::Pass);
    let expected = policy
        .version
        .as_ref()
        .and_then(|declared| declared.expected_version.clone());
    let captured = context
        .version
        .as_ref()
        .and_then(|facts| facts.captured_version.value().cloned());
    let resolved = expected
        .filter(|_| endorsed)
        .map(|value| (value, ReleaseVersionSource::ExpectedVersion))
        .or_else(|| captured.map(|value| (value, ReleaseVersionSource::GitTagCapture)));
    let (text, source) = resolved.ok_or_else(|| {
        let reason = match (endorsed, policy.version.is_some()) {
            (false, true) => "`release.expected_version` is configured but the Gate's version rule did not \
                 pass, and no exact tag yielded a `version` capture"
                .to_owned(),
            (true, true) | (false, false) => {
                "the `[version]` policy's pattern matched no tag carrying a `version` capture, and no \
                 `release.expected_version` resolved"
                    .to_owned()
            }
            (true, false) => "no `[version]` policy is configured, so there is no tag pattern a release \
                 version could be read from"
                .to_owned(),
        };
        BundleError::Release(ReleaseError::VersionUnavailable { reason })
    })?;
    Ok((
        ReleaseVersion::parse(&text).map_err(BundleError::Release)?,
        source,
    ))
}

