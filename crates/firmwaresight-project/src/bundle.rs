/// A verified bundle that has not been written yet, holding every byte it would write.
#[derive(Debug, Clone)]
pub struct BundlePlan {
    /// What the release owner authorizes before any write.
    pub preview: BundlePreview,
    content: BundleContent,
    checks: InputChecks,
}

impl BundlePlan {
    /// The directory name this bundle proposes inside the folder the release owner chose (§29):
    /// `<sanitized-project>-<release-version>-<release-id-short>`. It is a display name, not a path, which
    /// is what lets a UI show and confirm it without ever receiving a host path.
    #[must_use]
    pub fn proposed_directory_name(&self) -> &str {
        &self.content.directory_name
    }

    /// The `release-manifest.json` document exactly as written, for the CLI's `--json` contract (§34): the
    /// stdout copy and the bundle copy are one string, so they cannot be two documents.
    #[must_use]
    pub fn manifest_document(&self) -> &str {
        &self.content.manifest_json
    }

    /// Write the bundle.
    ///
    /// `fresh` is the same request re-collected after the preview — current source digests, current config,
    /// current Git facts, current acceptance set. Anything that moved since [`prepare`] invalidates the plan
    /// and nothing is written (§28). `overwrite` is the release owner's explicit authorization to replace an
    /// existing bundle directory (§30), honored only for a directory recognizable as a FirmwareSight release
    /// bundle (§32).
    ///
    /// # Errors
    ///
    /// [`BundleError::PlanStale`], [`BundleError::SourceArtifactChanged`],
    /// [`BundleError::ReleaseNotesChanged`], [`BundleError::DestinationExists`],
    /// [`BundleError::UnsafeDestination`], [`BundleError::WriteFailed`],
    /// [`BundleError::VerificationFailed`] or [`BundleError::Index`], as described on [`BundleError`].
    pub fn publish(
        &self,
        fresh: &BundleRequest<'_>,
        parent: &Path,
        overwrite: bool,
    ) -> Result<BundleOutcome, BundleError> {
        let again = observe(fresh)?;
        self.checks.compare_with(&again.checks)?;

        let display = self.content.directory_name.clone();
        let destination = parent.join(&display);
        if destination.exists() {
            if !overwrite {
                return Err(BundleError::DestinationExists { display });
            }
            if !is_recognizable_bundle(&destination)? {
                return Err(BundleError::UnsafeDestination {
                    display,
                    detail: "it holds no `release-manifest.json` this build can read as a FirmwareSight \
                             release bundle, so it is not a bundle this engine wrote"
                        .to_owned(),
                });
            }
        } else {
            std::fs::create_dir_all(parent).map_err(|error| BundleError::WriteFailed {
                name: ".".to_owned(),
                detail: io_detail(&error),
            })?;
        }

        // §31, in order: a unique sibling staging directory, the payload, the two indexes, verification of
        // the staged tree, and only then the rename that makes it somebody's bundle.
        let staging = sibling(parent, "staging");
        if let Err(error) = write_tree(&self.content, &staging) {
            discard(&staging);
            return Err(error);
        }
        if let Err(error) = verify_bundle(&staging) {
            discard(&staging);
            return Err(error);
        }

        let backup = match replace_directory(&staging, &destination, overwrite, &display) {
            Ok(backup) => backup,
            Err(error) => {
                discard(&staging);
                return Err(error);
            }
        };
        let verification = verify_bundle(&destination)?;
        if let Some(previous) = &backup {
            // The predecessor is discarded only once the new bundle is in place and verified (§31).
            std::fs::remove_dir_all(previous).map_err(|error| BundleError::WriteFailed {
                name: display.clone(),
                detail: format!(
                    "the new bundle is published; the bundle it replaced is still in the folder under \
                     its original name and could not be discarded ({})",
                    error.kind()
                ),
            })?;
        }

        Ok(BundleOutcome {
            plan_id: self.preview.plan_id.clone(),
            release_id: self.content.release_id.clone(),
            release_version: self.content.model.version.as_str().to_owned(),
            gate_run_id: self.content.model.gate_run_id.clone(),
            directory_name: display,
            manifest_sha256: self.content.manifest_sha256.clone(),
            replaced: backup.is_some(),
            verification,
        })
    }
}

