//! `--markdown <FILE>` (R6, ADR-0034 D6): a GFM reading copy of an analysis or a comparison.
//!
//! The contract this file holds: the document is written, it is GFM without HTML, it says what is absent
//! and what is unknown in words, the same input writes the same bytes, and an existing file is never
//! replaced (exit 6, `ERR-EXPORT-6001`, the visual exports' refusal).

use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};

static NEXT_TEMP: AtomicUsize = AtomicUsize::new(0);

const BASE: &str = "fixtures/elf/m2-objects/base/firmware.elf";
const BASE_MAP: &str = "fixtures/elf/m2-objects/base/firmware.map";
const TARGET: &str = "fixtures/elf/m2-objects/target/firmware.elf";
const TARGET_MAP: &str = "fixtures/elf/m2-objects/target/firmware.map";

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|parent| parent.parent())
        .expect("apps/cli lives at <root>/apps/cli")
        .to_path_buf()
}

fn run(args: &[&str]) -> Output {
    let output = Command::new(env!("CARGO_BIN_EXE_fwsight"))
        .args(args)
        .current_dir(repo_root())
        .output()
        .expect("the fwsight binary is built for its own tests");
    let stderr = String::from_utf8_lossy(&output.stderr).to_lowercase();
    assert!(!stderr.contains("panicked"), "the CLI panicked:\n{stderr}");
    output
}

struct TempDir(PathBuf);

impl TempDir {
    fn new() -> Self {
        let path = std::env::temp_dir().join(format!(
            "fwsight-markdown-{}-{}",
            std::process::id(),
            NEXT_TEMP.fetch_add(1, Ordering::SeqCst)
        ));
        let _ = std::fs::remove_dir_all(&path);
        std::fs::create_dir_all(&path).expect("temp dir");
        Self(path)
    }

    fn file(&self, name: &str) -> String {
        self.0.join(name).to_string_lossy().into_owned()
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn read(path: &str) -> String {
    std::fs::read_to_string(path).expect("the report was written")
}

fn diff_markdown(out: &str) -> Output {
    run(&[
        "diff",
        BASE,
        TARGET,
        "--old-map",
        BASE_MAP,
        "--new-map",
        TARGET_MAP,
        "--markdown",
        out,
    ])
}

#[test]
fn a_comparison_report_reads_in_the_report_grammar_without_html() {
    let dir = TempDir::new();
    let path = dir.file("compare.md");
    let output = diff_markdown(&path);
    assert!(output.status.success(), "{output:?}");
    let doc = read(&path);

    // Masthead, answer, facts, evidence, limits, footer, in that order.
    let order = [
        "# FirmwareSight · Comparison report",
        "> Nonvolatile / load image: **▲64 bytes**",
        "## Memory",
        "## What changed",
        "## Evidence",
        "## Limits",
        "Generated by FirmwareSight",
    ];
    let mut from = 0;
    for marker in order {
        let at = doc[from..]
            .find(marker)
            .unwrap_or_else(|| panic!("`{marker}` missing after {from}:\n{doc}"));
        from += at + marker.len();
    }
    assert!(
        doc.contains("| Nonvolatile / load image | 132 bytes | 196 bytes | ▲64 bytes | exact |")
    );
    // An added row has no delta, and says why instead of saying unknown or 0.
    assert!(
        doc.contains("| Added | — (one side not present) |"),
        "{doc}"
    );
    // No HTML anywhere: a tag-shaped run of text would be an inline element in a GFM renderer.
    assert!(
        !doc.contains("</") && !doc.contains("<br") && !doc.contains("<span"),
        "{doc}"
    );
    // Names from the file are inert: an underscore cannot start emphasis.
    assert!(doc.contains("imu\\_calibration"), "{doc}");
    // No path of the machine that ran it.
    assert!(!doc.contains("fixtures") && !doc.contains(":\\"), "{doc}");
}

#[test]
fn the_same_input_writes_the_same_bytes_and_an_existing_file_is_never_replaced() {
    let dir = TempDir::new();
    let first = dir.file("one.md");
    let second = dir.file("two.md");
    assert!(diff_markdown(&first).status.success());
    assert!(diff_markdown(&second).status.success());
    assert_eq!(read(&first), read(&second), "deterministic");

    let refused = diff_markdown(&first);
    assert_eq!(refused.status.code(), Some(6));
    assert!(String::from_utf8_lossy(&refused.stderr).contains("ERR-EXPORT-6001"));
    assert_eq!(
        read(&first),
        read(&second),
        "the existing file is untouched"
    );
}

#[test]
fn an_analysis_report_names_the_build_and_writes_unknown_and_limits_in_words() {
    let dir = TempDir::new();
    let path = dir.file("analysis.md");
    let output = run(&["analyze", TARGET, "--map", TARGET_MAP, "--markdown", &path]);
    assert!(output.status.success(), "{output:?}");
    let doc = read(&path);
    assert!(doc.starts_with("# FirmwareSight · Analysis report\n"));
    assert!(doc.contains("**Build:** firmware.elf · SHA-256 `3c9daa4f7c09"));
    assert!(doc.contains("> Nonvolatile / load image: **196 bytes"));
    assert!(doc.contains("| FLASH | 65536 bytes | 196 bytes |"), "{doc}");
    assert!(doc.contains("A mapped section range is not free space"));
    assert!(doc.contains("## Limits"));
    // The text report still goes to stdout; the Markdown file is a second, separate document.
    assert!(
        String::from_utf8_lossy(&output.stdout).starts_with("FirmwareSight · Analysis report\n")
    );
}

#[test]
fn two_exports_naming_one_file_are_refused_before_anything_is_written() {
    // R6 review S3: `--html` replaces its file, so it would silently overwrite the Markdown written first.
    let dir = TempDir::new();
    let same = dir.file("report.out");
    let refused = run(&[
        "diff",
        BASE,
        TARGET,
        "--old-map",
        BASE_MAP,
        "--new-map",
        TARGET_MAP,
        "--markdown",
        &same,
        "--html",
        &same,
    ]);
    assert_eq!(refused.status.code(), Some(6));
    let stderr = String::from_utf8_lossy(&refused.stderr);
    assert!(stderr.contains("ERR-EXPORT-6001"), "{stderr}");
    assert!(stderr.contains("same file"), "{stderr}");
    assert!(!Path::new(&same).exists(), "nothing was written");

    let analyze = run(&["analyze", BASE, "--markdown", &same, "--svg", &same]);
    assert_eq!(analyze.status.code(), Some(6));
    assert!(!Path::new(&same).exists(), "nothing was written");
}
